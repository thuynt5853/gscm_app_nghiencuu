PROCEDURE THANH_TOAN_UP_TONGDAT
(
   V_TONGDAT_ID IN NUMBER,
   V_DUONGSUID IN NUMBER,
   V_MALOAIVUVIEC IN VARCHAR2
)
AS
     V_DONID NUMBER;V_COUNT NUMBER;
  BEGIN 
        IF(V_MALOAIVUVIEC='2') THEN
            SELECT TD.DONID INTO V_DONID FROM ADS_TONGDAT_DOITUONG OT
            INNER JOIN ADS_TONGDAT TD ON TD.ID=OT.TONGDATID
            WHERE TD.ID=V_TONGDAT_ID AND OT.DUONGSUID=V_DUONGSUID;
            --------------------
            SELECT COUNT(*) INTO V_COUNT FROM DVCQG_THANH_TOAN TT
            WHERE tt.donid=V_DONID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND DUONGSU_ID=V_DUONGSUID;
            IF(V_COUNT=1)THEN
            UPDATE DVCQG_THANH_TOAN 
            SET TONGDATID=V_TONGDAT_ID
            WHERE DONID=V_DONID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND DUONGSU_ID=V_DUONGSUID;
             END IF;
        ELSIF(V_MALOAIVUVIEC='3') THEN
            SELECT TD.DONID INTO V_DONID FROM AHN_TONGDAT_DOITUONG OT
            INNER JOIN AHN_TONGDAT TD ON TD.ID=OT.TONGDATID
            WHERE TD.ID=V_TONGDAT_ID AND OT.DUONGSUID=V_DUONGSUID;
            ------------------
            SELECT COUNT(*) INTO V_COUNT FROM DVCQG_THANH_TOAN TT
            WHERE tt.donid=V_DONID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND instr(','||DUONGSU_IDS||',',','||V_DUONGSUID||',')>0;
            IF(V_COUNT=1)THEN
            UPDATE DVCQG_THANH_TOAN 
            SET TONGDATID=V_TONGDAT_ID
            WHERE DONID=V_DONID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND instr(','||DUONGSU_IDS||',',','||V_DUONGSUID||',')>0;
            END IF;

