FUNCTION CREATE_MA_TB_RANDOM
(
  V_MA_THONGBAO OUT VARCHAR2
) 
RETURN VARCHAR2
AS
    V_COUNTS_MATB NUMBER;V_MA_TB VARCHAR2(255):=NULL;
BEGIN
    SELECT  DBMS_RANDOM.STRING('x',10) INTO V_MA_TB FROM DUAL;
    SELECT CASE WHEN EXISTS (SELECT 1 FROM DVCQG_THANH_TOAN DVC WHERE  DVC.MA_THONGBAO = V_MA_TB) 
           THEN 1  ELSE 0 END INTO V_COUNTS_MATB FROM DUAL;
    -----------
    IF(V_COUNTS_MATB=1)THEN
         V_MA_THONGBAO:=PKG_DVCQG_APP.CREATE_MA_TB_RANDOM(V_MA_THONGBAO);
    ELSIF(V_COUNTS_MATB=0)THEN
         V_MA_THONGBAO:=V_MA_TB;     
    END IF;
  RETURN V_MA_THONGBAO;
END CREATE_MA_TB_RANDOM; 
PROCEDURE TT_REMOVE_TONGDAT
( 
  V_TONGDAT_ID IN NUMBER,
  V_MALOAIVUVIEC IN VARCHAR2,
  V_VALUE OUT NUMBER
)
IS  
V_COUNTS NUMBER(20);
BEGIN
     V_VALUE:=0;
     SELECT COUNT(*) INTO V_COUNTS FROM DVCQG_THANH_TOAN TT  WHERE TT.TONGDATID=V_TONGDAT_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC
      and TRANGTHAITHANHTOAN=1;--AND EXISTS(SELECT 'X' FROM DVCQG_GIAODICH GD WHERE GD.THANH_TOAN_ID=TT.ID)
     IF(V_COUNTS=0)THEN --update khi chưa phát sinh giao dịch
         UPDATE DVCQG_THANH_TOAN TT
         SET TONGDATID=NULL
         WHERE TT.TONGDATID=V_TONGDAT_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC;
         V_VALUE:=1;
    END IF;
END TT_REMOVE_TONGDAT;
PROCEDURE THANH_TOAN_DELETE_XLY
( 
  V_DONXULY_ID IN NUMBER,
  V_MALOAIVUVIEC IN VARCHAR2,
  V_VALUE OUT NUMBER
)
IS  
V_COUNTS NUMBER;V_ID_TT NUMBER;V_COUNT_TT NUMBER;V_COUNT_TP NUMBER;
BEGIN
     V_VALUE:=0;
     -------------
     SELECT COUNT(*) INTO V_COUNT_TT FROM DVCQG_THANH_TOAN TT  WHERE TT.DONXULY_ID=V_DONXULY_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND TRANGTHAITHANHTOAN=0;
     ----------------
    IF(V_COUNT_TT=1)THEN 
         SELECT TT.ID INTO V_ID_TT FROM DVCQG_THANH_TOAN TT   WHERE TT.DONXULY_ID=V_DONXULY_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND TRANGTHAITHANHTOAN=0;
         ---------
         DELETE DVCQG_GIAODICH TT
         WHERE TT.THANH_TOAN_ID=V_ID_TT;
    END IF;
    SELECT COUNT(*) INTO V_COUNTS FROM DVCQG_THANH_TOAN TT WHERE TT.DONXULY_ID=V_DONXULY_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND TRANGTHAITHANHTOAN=0
    AND EXISTS(SELECT 'X' FROM DVCQG_GIAODICH GD WHERE GD.THANH_TOAN_ID=TT.ID);
     IF(V_COUNTS=0)THEN 
        DELETE DVCQG_THANH_TOAN TT
        WHERE TT.DONXULY_ID=V_DONXULY_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC  AND TRANGTHAITHANHTOAN=0;
         ---------
