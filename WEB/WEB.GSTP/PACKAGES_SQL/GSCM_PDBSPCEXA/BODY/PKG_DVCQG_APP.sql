            IF(V_COUNT_TP=1)THEN
             DELETE TUPHAP_ANPHI TP
             WHERE  TP.MALOAIVUVIEC=V_MALOAIVUVIEC AND TP.DVCQG_TT_ID=V_ID_TT;
             END IF;
        V_VALUE:=1;
     END IF;    
