    IF(V_COUNT_TT=1)THEN 
         SELECT TT.ID INTO V_ID_TT FROM DVCQG_THANH_TOAN TT  WHERE TT.ANPHI_ID=V_ANPHI_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND TRANGTHAITHANHTOAN=0;
         DELETE DVCQG_GIAODICH TT
         WHERE TT.THANH_TOAN_ID=V_ID_TT;
    END IF;
        SELECT COUNT(*) INTO V_COUNTS FROM DVCQG_THANH_TOAN TT  WHERE TT.ANPHI_ID=V_ANPHI_ID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND TRANGTHAITHANHTOAN=0
        AND EXISTS(SELECT 'X' FROM DVCQG_GIAODICH GD WHERE GD.THANH_TOAN_ID=TT.ID);
    IF(V_COUNTS=0)THEN
         DELETE DVCQG_THANH_TOAN TT
         WHERE TT.ANPHI_ID=V_ANPHI_ID AND TT.MALOAIVUVIEC=V_MALOAIVUVIEC AND TT.TRANGTHAITHANHTOAN=0;
         SELECT COUNT(*) INTO V_COUNT_TP FROM TUPHAP_ANPHI TP WHERE TP.ANPHI_ID=V_ANPHI_ID AND TP.MALOAIVUVIEC=V_MALOAIVUVIEC AND TP.DVCQG_TT_ID=V_ID_TT;
            IF(V_COUNT_TP=1)THEN
             DELETE TUPHAP_ANPHI TP
             WHERE TP.ANPHI_ID=V_ANPHI_ID AND TP.MALOAIVUVIEC=V_MALOAIVUVIEC AND TP.DVCQG_TT_ID=V_ID_TT;
             END IF;
         V_VALUE:=1;
    END IF;

END THANH_TOAN_DELETE_ANPHI;
