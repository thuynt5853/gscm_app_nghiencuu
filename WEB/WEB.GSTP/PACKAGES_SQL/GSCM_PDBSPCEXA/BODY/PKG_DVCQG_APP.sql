            --------------
            SELECT COUNT(*) INTO V_COUNT FROM DVCQG_THANH_TOAN TT
            WHERE tt.donid=V_DONID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND DUONGSU_ID=V_DUONGSUID;
            IF(V_COUNT=1)THEN
            UPDATE DVCQG_THANH_TOAN 
            SET TONGDATID=V_TONGDAT_ID
            WHERE DONID=V_DONID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND DUONGSU_ID=V_DUONGSUID;
            END IF;
        ELSIF(V_MALOAIVUVIEC='6') THEN
