            WHERE DONID=V_DONID AND MALOAIVUVIEC=V_MALOAIVUVIEC AND instr(','||DUONGSU_IDS||',',','||V_DUONGSUID||',')>0;
            END IF;
        ELSIF(V_MALOAIVUVIEC='7') THEN
