FUNCTION  QT_NGUOIDUNG_SEARCH
( 
  V_DONVIID IN VARCHAR2,
  V_PHONGBANID IN	VARCHAR2,
  V_USERNAME IN VARCHAR2,
  V_HOTEN IN VARCHAR2 
)
RETURN SYS_REFCURSOR
IS 
    V_CURSOR sys_refcursor;
BEGIN
        OPEN V_CURSOR FOR 
            SELECT NULL LOAIUSER,T.TEN_ALIAS TENDONVI,NH.NAME TENNHOMNSD,PB.TENPHONGBAN,NSD.*
            FROM COVID_NGUOISUDUNG NSD
            INNER JOIN COVID_DV_TRUCTHUOC T ON NSD.DV_TRUCTHUOC=T.ID
            LEFT JOIN COVID_DM_CANBO CB ON CB.ID=NSD.CANBOID
            LEFT JOIN COVID_PHONGBAN PB ON PB.ID=CB.PHONGBANID
            LEFT JOIN COVID_NHOM_ND NH ON NH.ID=NSD.NHOM_ND_ID
            WHERE (V_DONVIID IS NULL OR (NSD.DV_TRUCTHUOC=V_DONVIID))
                AND (V_PHONGBANID IS NULL OR CB.PHONGBANID=V_PHONGBANID)
                AND (V_USERNAME IS NULL OR UPPER(NSD.USERNAME) LIKE '%'||UPPER(V_USERNAME)||'%')
                AND (V_HOTEN IS NULL OR ( (UPPER(NSD.HOTEN) LIKE '%'||UPPER(V_HOTEN)||'%')
                                          OR (UPPER(NSD.EMAIL) LIKE '%'||UPPER(V_HOTEN)||'%')
                                          OR (UPPER(NSD.DIENTHOAI) LIKE '%'||UPPER(V_HOTEN)||'%')
                                         )
                  )
               AND UPPER(NSD.USERNAME)!='ADMIN'   
            ORDER BY NSD.USERNAME;
 RETURN  V_CURSOR;   
END QT_NGUOIDUNG_SEARCH;

PROCEDURE DM_CANBO_SEARCH 
(
  vDV_TRUCTHUOC in varchar2,
  vPhongbanID in varchar2,
  vChucDanhID in varchar2,
  vChucVuID in varchar2,
  v_TrangThaiCongTac in varchar2,
  v_KeySearch in varchar2,
  CurrPageIndex in number,
  PageSize in number,
  CurReturn OUT sys_refcursor
) AS
  vmin_stt  number;  vmax_stt  number;vTotal  number;
BEGIN
    vmin_stt := (CurrPageIndex-1)*PageSize + 1;
	vmax_stt := CurrPageIndex*PageSize;
    ------
  OPEN CurReturn FOR
      SELECT D.TT,D.ID,D.MACANBO,D.HOTEN,D.CHUCDANH,D.CHUCVU,D.DONVI_TEN,D.TENPHONGBAN
       ,D.TOTAL,D.TRANGTHAI,D.NGUOITAO,D.NGUOISUA
                FROM 
                (SELECT COUNT(*) OVER()TOTAL,ROW_NUMBER() OVER(ORDER BY SUBSTR(A.HOTEN,INSTR(A.HOTEN,' ',-1)+ 1)) AS TT,A.ID,A.MACANBO,A.HOTEN,
                CD.TEN CHUCDANH,CV.TEN CHUCVU,DV.TEN_ALIAS DONVI_TEN,P.TENPHONGBAN
                ,(CASE A.HIEULUC WHEN 0 THEN u'Ngh\1ec9 c\00f4ng t\00e1c'  WHEN 1 THEN u'\0110ang c\00f4ng t\00e1c'  WHEN 2 THEN u'Ngh\1ec9 ph\00e9p'  WHEN 3 THEN u'D\1eebng x\00e9t x\1eed'  END) TRANGTHAI
                ,A.NGUOITAO,A.NGUOISUA
                FROM COVID_DM_CANBO A
                LEFT JOIN COVID_DV_TRUCTHUOC DV ON DV.ID=A.DV_TRUCTHUOC
                LEFT JOIN COVID_PHONGBAN P ON P.ID=A.PHONGBANID
                LEFT JOIN (SELECT B.ID,B.TEN FROM DM_DATAITEM B WHERE B.GROUPID = 12) CD ON A.CHUCDANHID=CD.ID
                LEFT JOIN (SELECT C.ID,C.TEN FROM DM_DATAITEM C WHERE C.GROUPID = 13) CV ON A.CHUCVUID=CV.ID
                WHERE (vDV_TRUCTHUOC IS NULL OR A.DV_TRUCTHUOC=vDV_TRUCTHUOC)
                AND (vChucDanhID IS NULL OR CD.ID=vChucDanhID)
                AND (vChucVuID IS NULL OR CV.ID=vChucVuID)
                AND (vPhongbanID IS NULL OR A.PHONGBANID=vPhongbanID)
                AND (v_TrangThaiCongTac IS NULL OR A.HIEULUC=v_TrangThaiCongTac)
                AND (v_KeySearch IS NULL 
                   OR(UPPER(A.HOTEN) LIKE '%'||UPPER(v_KeySearch)||'%')
                   OR(UPPER(A.MACANBO) LIKE '%'||UPPER(v_KeySearch)||'%')
                   OR(UPPER(A.DIACHI) LIKE '%'||UPPER(v_KeySearch)||'%')
                 )

       ) D WHERE D.TT BETWEEN VMIN_STT AND VMAX_STT;
END DM_CANBO_SEARCH;
PROCEDURE  DM_DATAITEM_GETBYGROUPNAME
( vGroupName in nvarchar2,
	curReturn    OUT       sys_refcursor
)
IS 
BEGIN
OPEN curReturn FOR  
    SELECT
        i.ID,i.MA,i.TEN,((Case SOCAP WHen 2 then '...' when 3 then '......' else '' End)||i.Ten) MA_TEN
    FROM DM_DATAITEM i
    inner join DM_DATAGROUP g on g.ID=i.GROUPID
    Where g.MA=vGroupName and i.HIEULUC=1
    Order By i.ARRTHUTU;
END DM_DATAITEM_GETBYGROUPNAME;
FUNCTION THONGKE_F_HOTEN
(
  V_CANBOID IN NVARCHAR2 DEFAULT NULL
)
RETURN SYS_REFCURSOR
AS
V_CURSOR sys_refcursor; V_EXPORT_TEXT CLOB;  V_EXPORT_TEXT_ITEM CLOB;F0 NUMBER;F1 NUMBER;F2 NUMBER;F3 NUMBER;F4 NUMBER;
BEGIN
     DBMS_LOB.CREATETEMPORARY(V_EXPORT_TEXT,true);     DBMS_LOB.CREATETEMPORARY(V_EXPORT_TEXT_ITEM,true);    
    -----------
     DBMS_LOB.APPEND(V_EXPORT_TEXT,' 
            <ul class="thongke" style="text-align: left;">
      ');              
    FOR item in (
                 SELECT XD.ID,XD.TEN FROM COVID_XD_F XD
                 WHERE EXISTS (SELECT 'X' FROM COVID_DANGKY DK WHERE DK.XACDINH_F=XD.ID AND DK.NGAYTAO>TO_DATE('30/04/2021','dd/MM/yyyy'))
                 ORDER BY XD.ORDERS
                )
     LOOP
            DBMS_LOB.CREATETEMPORARY(V_EXPORT_TEXT_ITEM,true); 
            DBMS_LOB.APPEND(V_EXPORT_TEXT,'<li><span style="color: #ca2020">'||item.id||'</span>: ');  
           FOR item_a IN (SELECT CB.HOTEN||' - '||DV.TEN_ALIAS HOTEN FROM COVID_DANGKY DK 
                            LEFT JOIN COVID_DM_CANBO CB ON CB.ID=DK.CANBOID
                            LEFT JOIN COVID_DV_TRUCTHUOC DV ON DV.ID=CB.DV_TRUCTHUOC
                            WHERE DK.XACDINH_F=item.ID AND DK.NGAYTAO>TO_DATE('30/04/2021','dd/MM/yyyy')
                            GROUP BY CB.HOTEN,DV.TEN_ALIAS
                      )
            LOOP
                DBMS_LOB.APPEND(V_EXPORT_TEXT_ITEM,item_a.HOTEN||', ');  
            END LOOP;
            DBMS_LOB.APPEND(V_EXPORT_TEXT,RTRIM(V_EXPORT_TEXT_ITEM,', ')||'</li>'); 
     END LOOP;
     DBMS_LOB.APPEND(V_EXPORT_TEXT,'</ul>');  
    ----------
    OPEN V_CURSOR FOR
        SELECT V_EXPORT_TEXT TEXT_REPORT FROM dual;
         dbms_lob.freetemporary(V_EXPORT_TEXT);
        dbms_lob.freetemporary(V_EXPORT_TEXT_ITEM);
        RETURN V_CURSOR;  
END THONGKE_F_HOTEN;
