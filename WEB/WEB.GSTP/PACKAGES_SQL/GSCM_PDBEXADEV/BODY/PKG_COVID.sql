FUNCTION COVID_DANGKY_DS 
(
  V_CANBOID IN NVARCHAR2 DEFAULT NULL,
  PageIndex	in	NUMBER,
  PageSize	in	NUMBER
)
RETURN SYS_REFCURSOR
AS
      MININDEX	number;  MAXINDEX	number;
      V_CURSOR sys_refcursor;
begin
  MININDEX := pagesize*(PAGEINDEX - 1) + 1;
  MAXINDEX := PAGEINDEX*pagesize ;
  OPEN v_cursor FOR
 select DS.* from (
                SELECT COUNT(*) OVER()COUNTALL,ROW_NUMBER() OVER (ORDER BY DK.NGAYTAO DESC) STT
                ,TO_CHAR(DK.NGAYTAO,'dd/MM/yyyy HH24:MI:SS') NGAYTAO,TO_CHAR(DK.NGAYSUA,'dd/MM/yyyy HH24:MI:SS') NGAYSUA,DK.NGUOITAO,DECODE(DK.TIEPXUCGAN_BN,0,'Không',1,'Có')TIEPXUCGAN_BN
                ,DECODE(DK.SOT,0,'Không','Có')SOT,DK.GHICHU
                ,( DECODE(TO_CHAR(DK.CACHLY_TUNGAY,'dd/MM/yyyy'),'01/01/0001',NULL,'Từ ngày '||TO_CHAR(DK.CACHLY_TUNGAY,'dd/MM/yyyy'))
                ||DECODE(TO_CHAR(DK.CACHLY_DENGAY,'dd/MM/yyyy'),'01/01/0001',NULL,'<br/> Đến ngày '||TO_CHAR(DK.CACHLY_DENGAY,'dd/MM/yyyy')) )TIME_CACHLY
                FROM COVID_DANGKY DK
                 INNER JOIN COVID_DM_CANBO CB ON CB.ID=DK.CANBOID  
                 LEFT JOIN COVID_DV_TRUCTHUOC TT ON TT.ID=CB.DV_TRUCTHUOC
                 LEFT JOIN COVID_PHONGBAN PB ON PB.ID=CB.PHONGBANID
                 --LEFT JOIN COVID_NGUOISUDUNG ND ON CO.CANBOID=ND.CANBOID
                WHERE (V_CANBOID IS NULL OR DK.CANBOID=V_CANBOID)  AND DK.NGAYTAO>=TO_DATE('30/04/2021','dd/MM/yyyy')
        ) DS WHERE DS.STT>=MININDEX AND DS.STT<=MAXINDEX;
    RETURN v_cursor;   
END COVID_DANGKY_DS;
