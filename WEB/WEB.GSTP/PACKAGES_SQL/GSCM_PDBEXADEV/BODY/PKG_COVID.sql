PROCEDURE COVID_NGUOIDUNG_INS_UP
(
    V_ID	IN	NUMBER,
    V_USERNAME	IN	VARCHAR2,
    V_PASSWORD	IN	VARCHAR2,
    V_HOTEN	IN	VARCHAR2,
    V_CANBOID	IN	NUMBER,
    V_HIEULUC	IN	NUMBER,
    V_DIENTHOAI	IN	VARCHAR2,
    V_EMAIL	IN	VARCHAR2,
    V_NGUOITAO	IN	VARCHAR2,
    V_NGAYTAO	IN	DATE,
    V_NHOM_ND_ID	IN	NUMBER,
    V_DV_TRUCTHUOC	IN	NUMBER,
    V_PHONGBANID	IN	NUMBER,
    V_THONGBAO OUT VARCHAR2
)
AS
            V_COUNT_USER NUMBER;
BEGIN 
    IF v_ID=0 THEN
      SELECT COUNT(*) INTO V_COUNT_USER FROM COVID_NGUOISUDUNG ND WHERE ND.USERNAME=V_USERNAME;
        IF(V_COUNT_USER=0) THEN
              INSERT INTO COVID_NGUOISUDUNG
               (ID,USERNAME,PASSWORD,HOTEN,DONVIID,CANBOID,HIEULUC,DIENTHOAI,EMAIL,NGUOITAO,NGAYTAO,NGUOISUA,NGAYSUA
               ,NOT_IN_PMQLCB,NHOM_ND_ID,DV_TRUCTHUOC,PHONGBANID)
             VALUES  (COVID_NGUOISUDUNG_SEQ.NEXTVAL,V_USERNAME,V_PASSWORD,V_HOTEN,1,V_CANBOID,V_HIEULUC,V_DIENTHOAI,V_EMAIL,V_NGUOITAO,sysdate,V_NGUOITAO,sysdate
               ,1,V_NHOM_ND_ID,V_DV_TRUCTHUOC,V_PHONGBANID);
        ELSE
          V_THONGBAO:='Tài khoản này đã tồn tại, bạn phải chọn tài khoản khác.';
        END IF;
     ELSE 
          UPDATE COVID_NGUOISUDUNG
            SET  
                HOTEN= V_HOTEN,
                CANBOID= V_CANBOID,
                HIEULUC= V_HIEULUC,
                DIENTHOAI= V_DIENTHOAI,
                EMAIL= V_EMAIL,
                NGUOISUA= V_NGUOITAO,
                NGAYSUA= V_NGAYTAO,
                NHOM_ND_ID= V_NHOM_ND_ID,
                DV_TRUCTHUOC= V_DV_TRUCTHUOC,
                PHONGBANID= V_PHONGBANID
            WHERE ID=v_ID;
     END IF;     
END COVID_NGUOIDUNG_INS_UP;
