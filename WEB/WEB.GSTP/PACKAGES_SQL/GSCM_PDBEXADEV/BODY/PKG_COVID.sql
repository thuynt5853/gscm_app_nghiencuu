PROCEDURE DELETE_CANBO_ID
(    
  V_ID	IN	NUMBER,
  V_THONGBAO OUT VARCHAR2
)
AS  
   COUNT_CANBO NUMBER;V_USERNAME_LIST VARCHAR2(1000);
BEGIN  
     SELECT COUNT(*)INTO COUNT_CANBO FROM COVID_NGUOISUDUNG ND WHERE ND.CANBOID=V_ID;
     IF(COUNT_CANBO>0) THEN
        SELECT LISTAGG(ND.USERNAME, ',')  WITHIN GROUP (ORDER BY ND.ID) INTO V_USERNAME_LIST  
        FROM COVID_NGUOISUDUNG ND
        WHERE ND.CANBOID=V_ID;
        V_THONGBAO:='Đã tồn tại tài khoản người dùng: (<b>'||V_USERNAME_LIST||'</b>), bạn phải xóa tài khoản người dùng trước.';
     ELSE
         DELETE COVID_DM_CANBO CB  WHERE CB.ID=V_ID;
     END IF;
END;
PROCEDURE DELETE_NGUOIDUNG_ID
(    
  V_ID	IN	NUMBER,
  V_THONGBAO OUT VARCHAR2
)
AS  
   COUNT_USER NUMBER;V_USERNAME_LIST VARCHAR2(1000);COUNT_QUANTRI NUMBER;
BEGIN  
     SELECT COUNT(*)INTO COUNT_QUANTRI FROM COVID_NGUOISUDUNG NSD WHERE NSD.NHOM_ND_ID=1 AND NSD.ID=V_ID;
