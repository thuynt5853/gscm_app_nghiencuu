PROCEDURE  USER_LOGIN
(
  V_USERNAME in VARCHAR2,
  V_PASSWORD in VARCHAR2,
  CurReturn OUT sys_refcursor 
) 
AS 
BEGIN
       open CurReturn for
           SELECT ND.ID USERID,ND.USERNAME,CB.ID CANBO_ID,CB.HOTEN,TT.ID DV_TRUCTHUOID,TT.TEN_ALIAS DV_TRUCTHUOC_TEN
           ,PB.ID PHONGBANID,PB.TENPHONGBAN,CB.SODIENTHOAI,CB.EMAIL ,ND.NHOM_ND_ID
           FROM COVID_NGUOISUDUNG ND
           LEFT JOIN COVID_DM_CANBO CB ON CB.ID=ND.CANBOID  
           LEFT JOIN COVID_DV_TRUCTHUOC TT ON TT.ID=CB.DV_TRUCTHUOC
           LEFT JOIN COVID_PHONGBAN PB ON PB.ID=CB.PHONGBANID
           WHERE LOWER(ND.USERNAME)=LOWER(V_USERNAME) AND ND.PASSWORD=LOWER(V_PASSWORD)
           AND ND.HIEULUC=1;
END USER_LOGIN;
