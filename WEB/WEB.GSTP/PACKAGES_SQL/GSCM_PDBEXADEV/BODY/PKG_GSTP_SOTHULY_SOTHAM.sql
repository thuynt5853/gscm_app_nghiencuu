			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOKN || CHR(10) ||
					TO_CHAR(T2.NGAYKN,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT)  v_KN_27
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHN_SOTHAM_KHANGNGHI T2 ON T1.v_VUANID=T2.DONID
