					decode(T2.SOQD,null,null,'QĐXX:'||T2.SOQD ||', ')||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY') ||DL1.TENDUONGSU ||PT1.TENDUONGSU
                    ||DECODE(QHLD.ID,NULL,NULL,'Quá hạn luật định')
				) WITHIN GROUP (ORDER BY T1.v_STT)  v_GHICHU_27
			FROM 
				TABLE(v_ARRAY) T1 
                LEFT JOIN AKT_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID and T2.quyetdinhid=46 --47-DS. Quyết định đưa vụ án ra xét xử sơ thẩm
                LEFT JOIN DON_CHITIET PT ON PT.DONID=T1.v_VUANID AND PT.LOAIDON=5 -- DC.LOAIDON=5 Đơn có yêu cầu phản tố
                LEFT JOIN ( 
                            SELECT 'YCPT:'||LISTAGG(DS.TENDUONGSU,',')  WITHIN GROUP (ORDER BY TENDUONGSU) TENDUONGSU,CH.DONCHITIETID
                            FROM DON_DUONGSU_CHITIET CH 
                            LEFT JOIN AKT_DON_DUONGSU DS ON DS.ID=CH.DUONGSUID
                            GROUP BY CH.DONCHITIETID
                            ) PT1 ON PT1.DONCHITIETID=PT.ID
                LEFT JOIN DON_CHITIET DL ON DL.DONID=T1.v_VUANID AND DL.LOAIDON=6 -- DC.LOAIDON=6 Đơn có yêu cầu độc lập
                LEFT JOIN ( 
                            SELECT 'YCĐL:'||LISTAGG(DS.TENDUONGSU,',')  WITHIN GROUP (ORDER BY TENDUONGSU) TENDUONGSU,CH.DONCHITIETID
                            FROM DON_DUONGSU_CHITIET CH 
                            LEFT JOIN AKT_DON_DUONGSU DS ON DS.ID=CH.DUONGSUID
                            GROUP BY CH.DONCHITIETID
                            ) DL1 ON DL1.DONCHITIETID=DL.ID
                 LEFT JOIN (                       
                            SELECT TL.ID FROM AKT_SOTHAM_THULY TL
