				T1.v_STT				
		) LOOP
			v_ARRAY(ITEM.v_STT).v_KN_27:=ITEM.v_KN_27;
		END LOOP;

		-- v_CHUYENHS_TA_PT_28 - CHUYỂN HỒ SƠ CHO TÒA ÁN CẤP PHÚC THẨM Ngày tháng năm - 28 - 
        FOR ITEM IN (
                    SELECT 
                        T1.v_STT, 
                        LISTAGG(
                            TO_CHAR(T2.NGAYGIAO,'DD/MM/YYYY')
                            , CHR(10)
                        ) WITHIN GROUP (ORDER BY T1.v_STT) v_CHUYENHS_TA_PT_28
                    FROM 
                        TABLE(v_ARRAY) T1 
                        LEFT JOIN Ahn_CHUYEN_NHAN_AN T2 ON  T1.v_VUANID=T2.VUANID
                        LEFT JOIN DM_TOAAN TA ON TA.ID=T2.TOANHANID
                        WHERE TRUONGHOPGIAONHANID in(267,268,269) and TA.MA_TEN is not null
                        --267 Do có kháng cáo phúc thẩm 
                        --268 Do có kháng cáo và kháng nghị phúc thẩm 
                        --269 Do có kháng nghị phúc thẩm
                    GROUP BY T1.v_STT
                ) LOOP
                    v_ARRAY(ITEM.v_STT).v_CHUYENHS_TA_PT_28:=ITEM.v_CHUYENHS_TA_PT_28;
                END LOOP;
--		-- v_QD_TA_PT_29 - QUYẾT ĐỊNH CỦA TÒA ÁN CẤP PHÚC THẨM Số, ngày tháng năm Tóm tắt nội dung phần quyết định - 29 - 
        FOR ITEM IN (
                SELECT 
                    T1.v_STT
                    ,T3.SOQD|| CHR(10) ||TO_CHAR(T3.NGAYQD,'DD/MM/YYYY')|| CHR(10) || T3.NOIDUNGQD|| CHR(10)||
                    T2.SOBANAN|| CHR(10) || TO_CHAR(T2.NGAYTUYENAN,'DD/MM/YYYY') || CHR(10) ||  T2.NOIDUNGQD|| CHR(10) 
                    v_QD_TA_PT_29
                FROM 
                    TABLE(v_ARRAY) T1 
                    LEFT JOIN (SELECT B.ID,B.DONID,B.SOBANAN,B.NGAYTUYENAN,BKQ.TEN NOIDUNGQD 
                                            FROM AHN_PHUCTHAM_BANAN B
                                            LEFT JOIN DM_KETQUA_PHUCTHAM BKQ ON BKQ.ID = B.KETQUAPHUCTHAMID) T2 ON T1.v_VUANID=T2.DONID
                    LEFT JOIN (SELECT Q.SOQD, Q.NGAYQD,Q.DONID,Q.QUYETDINHID,KQ.TEN NOIDUNGQD 
                                            FROM AHN_PHUCTHAM_QUYETDINH Q 
                                            LEFT JOIN DM_QD_QUYETDINH D ON D.ID=Q.QUYETDINHID 
                                            LEFT JOIN DM_KETQUA_PHUCTHAM KQ ON KQ.ID = Q.KETQUAID
                                                    WHERE D.KET_THUC = 1) T3 ON T1.v_VUANID=T3.DONID
            ) LOOP
                v_ARRAY(ITEM.v_STT).v_QD_TA_PT_29:=ITEM.v_QD_TA_PT_29;
            END LOOP;
		-- v_GHICHU_30 - GHI CHÚ - 30 - 
FOR ITEM IN (
			SELECT 
				T1.v_STT, 
                LISTAGG(
					decode(T2.SOQD,null,null,'QĐXX:'||T2.SOQD ||', ')||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY') ||DL1.TENDUONGSU ||PT1.TENDUONGSU
                    ||DECODE(QHLD.ID,NULL,NULL,'Quá hạn luật định')
				) WITHIN GROUP (ORDER BY T1.v_STT)  v_GHICHU_30
			FROM 
				TABLE(v_ARRAY) T1 
                LEFT JOIN AHN_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID and T2.quyetdinhid=46 --47-DS. Quyết định đưa vụ án ra xét xử sơ thẩm
                LEFT JOIN DON_CHITIET PT ON PT.DONID=T1.v_VUANID AND PT.LOAIDON=5 -- DC.LOAIDON=5 Đơn có yêu cầu phản tố
                LEFT JOIN ( 
                            SELECT 'YCPT:'||LISTAGG(DS.TENDUONGSU,',')  WITHIN GROUP (ORDER BY TENDUONGSU) TENDUONGSU,CH.DONCHITIETID
                            FROM DON_DUONGSU_CHITIET CH 
                            LEFT JOIN AHN_DON_DUONGSU DS ON DS.ID=CH.DUONGSUID
                            GROUP BY CH.DONCHITIETID
                            ) PT1 ON PT1.DONCHITIETID=PT.ID
                LEFT JOIN DON_CHITIET DL ON DL.DONID=T1.v_VUANID AND DL.LOAIDON=6 -- DC.LOAIDON=6 Đơn có yêu cầu độc lập
                LEFT JOIN ( 
                            SELECT 'YCĐL:'||LISTAGG(DS.TENDUONGSU,',')  WITHIN GROUP (ORDER BY TENDUONGSU) TENDUONGSU,CH.DONCHITIETID
                            FROM DON_DUONGSU_CHITIET CH 
                            LEFT JOIN AHN_DON_DUONGSU DS ON DS.ID=CH.DUONGSUID
                            GROUP BY CH.DONCHITIETID
                            ) DL1 ON DL1.DONCHITIETID=DL.ID
                 LEFT JOIN (                       
                            SELECT TL.ID FROM AHN_SOTHAM_THULY TL
                            LEFT JOIN AHN_SOTHAM_QUYETDINH QSV ON TL.DONID=QSV.DONID
                            LEFT JOIN DM_QD_LOAI QDL ON QSV.LOAIQDID=QDL.ID
                            LEFT JOIN AHN_SOTHAM_BANAN BA ON BA.DONID =TL.DONID
                            WHERE BA.ID IS NOT NULL and BA.TK_ISQUAHAN =1 --phải lấy check ở quấ hạn luật định ở bản án
                            GROUP BY TL.ID )QHLD ON QHLD.ID=T1.v_THULYID           
                GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_GHICHU_30:=ITEM.v_GHICHU_30;
		END LOOP;
		--
	END;
