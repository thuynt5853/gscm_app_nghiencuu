                            GROUP BY TL.ID 
                            )QHLD ON QHLD.ID=T1.v_THULYID           
                GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_GHICHU_25:=ITEM.v_GHICHU_25;
		END LOOP;
	END;
