		 in_TOAANCAPCON IN NVARCHAR2,
		 in_NGAYBATDAU IN NVARCHAR2,
		 in_NGAYKETTHUC IN NVARCHAR2,
		 curReturn OUT SYS_REFCURSOR
	) AS
		v_ARRAY T_KINHTE_SOTHAM;
		v_IDS T_ID;
	BEGIN
		--
		--TÒA ÁN CẤP CON
		v_IDS:=T_ID();
		IF (in_TOAANCAPCON='TRUE') THEN
			SELECT R_ID(ID) BULK COLLECT INTO v_IDS FROM DM_TOAAN WHERE CAPCHAID=in_TOAANID;
		END IF;
		v_IDS.EXTEND();
		v_IDS(v_IDS.COUNT):=R_ID(in_TOAANID);
		--
		--XAC DINH ID THU LY AN THEO THAM SO
		SELECT R_KINHTE_SOTHAM(
			v_STT=>row_number() over (order by TL.ID),
			v_THULYID=>TL.ID,
			v_VUANID=>TL.DONID,
			v_TOAANID=>TL.TOAANID,
			v_QUANHEPHAPLUATID=>NULL,
			v_TL_1=>NULL,
			v_ND_NYC_2=>NULL,
			v_BDNLQ_KDTM_3=>NULL,
			v_DKK_CQTC_4=>NULL,
			v_NGUOI_QLNVLQ_5=>NULL,
			v_NGUOIBV_QLICHHP_DS_6=>NULL,
			v_QHPLKHITL_7=>NULL,
			v_ADBPKCTT_8=>NULL,
			v_CHUYENHS_VUVIEC_9=>NULL,
			v_TDC_10=>NULL,
			v_DC_11=>NULL,
			v_LYDO_12=>NULL,
			v_CONGNHAN_THOATHUAN_DS_13=>NULL,
			v_HDXX_VKS_TKPT_14=>NULL,
			v_BA_QDST_15=>NULL,
			v_QHPLTADAGQ_16=>NULL,
			v_TTND_BA_QD_TA_ST_17=>NULL,
			v_KQGQYC_HUYQDCABIET_18=>NULL,
			v_APDUNGANLE_19=>NULL,
			v_GQVA_TTRG_20=>NULL,
			v_COYEUTONUOCNGOAI_21=>NULL,
			v_VIEC_KDTM_22=>NULL,
			v_KC_23=>NULL,
			v_KN_24=>NULL,
			v_CHUYENHS_TA_PT_25=>NULL,
			v_QD_TA_PT_26_=>NULL,
			v_GHICHU_27=>NULL,
            V_NGAYTHULY=>NULL,
            V_SOTHULY=>NULL,
             V_QUANHEPHAPLUAT_NAME=>TL.QUANHEPHAPLUAT_NAME,
            V_PT_RUTKINHNGHIEM=>NULL
		)
--		BULK COLLECT INTO v_ARRAY
--		FROM AKT_SOTHAM_THULY TL INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
--		WHERE
--			NGAYTHULY BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY');
--		--
--		--THONG TIN SO THU LY
--		FILL_KINHTE_SOTHAM(v_ARRAY);
		BULK COLLECT INTO v_ARRAY
        FROM (
                SELECT TL.*
                FROM AKT_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')

                UNION 
                SELECT TL.*
                FROM AKT_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND 
                    (NOT EXISTS (SELECT  STQD.* FROM AKT_SOTHAM_QUYETDINH STQD 
                        INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 WHERE TL.DONID = STQD.DONID)
                    AND NOT EXISTS (SELECT BA.* FROM AKT_SOTHAM_BANAN BA WHERE TL.DONID = BA.DONID))


                UNION 
                SELECT TL.*
                FROM AKT_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND  
                    (EXISTS (SELECT  STQD.* FROM AKT_SOTHAM_QUYETDINH STQD 
                        INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 
                        WHERE TL.DONID = STQD.DONID AND STQD.NGAYQD BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')
                        )
                    OR EXISTS (SELECT BA.* FROM AKT_SOTHAM_BANAN BA 
                               WHERE TL.DONID = BA.DONID AND BA.NGAYTUYENAN BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')))


            ) TL;
            FILL_KINHTE_SOTHAM(v_ARRAY);
		/*--
		FOR ITEM IN (SELECT * FROM TABLE(v_ARRAY)) LOOP
			DBMS_OUTPUT.PUT_LINE (ITEM.v_STT||' - '||ITEM.v_THULYID);
		END LOOP;
		--*/
		OPEN curReturn FOR SELECT * FROM TABLE(v_ARRAY) --ORDER BY  REGEXP_REPLACE(V_SOTHULY, '[^0-9]'),V_NGAYTHULY;
        ORDER by EXTRACT(YEAR FROM  V_NGAYTHULY),to_number(REGEXP_REPLACE(V_SOTHULY, '[^0-9]')),V_NGAYTHULY;
		--
	EXCEPTION 
		WHEN OTHERS THEN 
			RAISE_APPLICATION_ERROR(-20000, sqlerrm);
	END;
	PROCEDURE FILL_KINHTE_SOTHAM
	(
		v_ARRAY IN OUT T_KINHTE_SOTHAM
	) AS
        COLUMN_5 CLOB;
        COLUMN_6 CLOB;

            COLUMN_12 CLOB;
            COLUMN_22 VARCHAR(10);
	BEGIN	
		--v_ARRAY:=T_KINHTE_SOTHAM();
		-- v_TL_1 - THỤ LÝ Số, ngày tháng năm - 1 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				T2.QUANHEPHAPLUATID v_QUANHEPHAPLUATID,
				T2.SOTHULY || CHR(10) || TO_CHAR(T2.NGAYTHULY,'DD/MM/YYYY') v_TL_1,
                T2.NGAYTHULY  V_NGAYTHULY,T2.SOTHULY V_SOTHULY
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AKT_SOTHAM_THULY T2 ON T1.v_THULYID=T2.ID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_TL_1:=ITEM.v_TL_1;
			v_ARRAY(ITEM.v_STT).v_QUANHEPHAPLUATID:=ITEM.v_QUANHEPHAPLUATID;
            v_ARRAY(ITEM.v_STT).V_NGAYTHULY:=ITEM.V_NGAYTHULY;v_ARRAY(ITEM.v_STT).V_SOTHULY:=ITEM.V_SOTHULY;
		END LOOP;

		-- v_ND_NYC_2 - NGUYÊN ĐƠN HOẶC NGƯỜI YÊU CẦU Họ tên, địa chỉ. Họ tên người đại diện, chức vụ, địa chỉ - 2 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU || '; ' ||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
                         DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_ND_NYC_2
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI 
                    FROM AKT_DON_DUONGSU ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='NGUYENDON' --NGUYÊN ĐƠN
                     LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                    LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID  
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_ND_NYC_2:=ITEM.v_ND_NYC_2;
		END LOOP;

		-- v_BDNLQ_KDTM_3 - BỊ ĐƠN NGƯỜI LIÊN QUAN TRONG VIỆC KINH DOANH THƯƠNG MẠI Họ tên, địa chỉ. Họ tên người đại diện, chức vụ, địa chỉ - 3 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU||';'||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
						 DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_BDNLQ_KDTM_3
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI 
                FROM AKT_DON_DUONGSU ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='BIDON' --BỊ ĐƠN
                LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID  
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_BDNLQ_KDTM_3:=ITEM.v_BDNLQ_KDTM_3;
		END LOOP;

		-- v_DKK_CQTC_4 - ĐƠN KHỞI KIỆN CỦA CƠ QUAN, TỔ CHỨC - 4 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(MAX(T2.LOAIDUONGSU),2,'Cơ quan',3,'Tổ chức','') v_DKK_CQTC_4
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AKT_DON_DUONGSU T2 ON T2.ISDAIDIEN=1 AND T1.v_VUANID=T2.DONID
        GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_DKK_CQTC_4:=ITEM.v_DKK_CQTC_4;
		END LOOP;

		-- v_NGUOI_QLNVLQ_5 - NGƯỜI CÓ QUYỀN LỢI, NGHĨA VỤ LIÊN QUAN Họ tên, địa chỉ. Họ tên người đại diện, chức vụ, địa chỉ - 5 -
        FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU || '; ' ||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
                         DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_NGUOI_QLNVLQ_5
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI 
                    FROM AKT_DON_DUONGSU ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='QUYENNVLQ' --NGUYÊN ĐƠN
                     LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                    LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID  
			GROUP BY T1.v_STT
		) LOOP
