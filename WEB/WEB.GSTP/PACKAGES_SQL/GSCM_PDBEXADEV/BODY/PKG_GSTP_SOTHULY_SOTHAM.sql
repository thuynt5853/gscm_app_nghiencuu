			v_ARRAY(ITEM.v_STT).v_GHICHU_27:=ITEM.v_GHICHU_27;
		END LOOP;
		--
	END;
    PROCEDURE SO_HANHCHINH_SOTHAM
	(
		 in_TOAANID IN NUMBER,
		 in_TOAANCAPCON IN NVARCHAR2,
		 in_NGAYBATDAU IN NVARCHAR2,
		 in_NGAYKETTHUC IN NVARCHAR2,
		 curReturn OUT SYS_REFCURSOR
	) AS
		v_ARRAY T_HANHCHINH_SOTHAM;
		v_IDS T_ID;
	BEGIN
		--
		--TÒA ÁN CẤP CON
		v_IDS:=T_ID();
		IF (in_TOAANCAPCON='TRUE') THEN
			SELECT R_ID(ID) BULK COLLECT INTO v_IDS FROM DM_TOAAN WHERE CAPCHAID=in_TOAANID;
		END IF;
		v_IDS.EXTEND();
		v_IDS(v_IDS.COUNT):=R_ID(in_TOAANID);
		--
		--XAC DINH ID THU LY AN THEO THAM SO
		SELECT R_HANHCHINH_SOTHAM(
			v_STT=>row_number() over (order by TL.ID),
			v_THULYID=>TL.ID,
			v_VUANID=>TL.DONID,
			v_TOAANID=>TL.TOAANID,
			v_QUANHEPHAPLUATID=>NULL,
			v_TL_1=>NULL,
			v_NGUOIKK_2=>NULL,
			v_NGUOIBKK_3=>NULL,
			v_NGUOI_QLNVLQ_4=>NULL,
			v_NGUOIBV_QLIHP_DS_5=>NULL,
			v_QHPL_6=>NULL,
			v_ADBPKCTT_7=>NULL,
			v_CHUYENHS_VA_8=>NULL,
			v_TDC_9=>NULL,
			v_DC_10=>NULL,
			v_LYDO_11=>NULL,
			v_HDXX_VKS_TKPT_12=>NULL,
			v_BA_ST_13=>NULL,
			v_TTND_BA_QD_TA_ST_14=>NULL,
			v_KN_CQNN_XXTN_15=>NULL,
			v_DOITHOAI_16=>NULL,
			v_APDUNGANLE_17=>NULL,
			v_GQ_TTRG_18=>NULL,
			v_GQYCBTTH_19=>NULL,
			v_COYEUTONUOCNGOAI_20=>NULL,
			v_KC_21=>NULL,
			v_KN_22=>NULL,
			v_CHUYENHS_TA_PT_23=>NULL,
			v_QD_TA_PT_24=>NULL,
			v_GHICHU_25=>NULL,
            V_NGAYTHULY=>NULL,
            V_SOTHULY=>NULL,
            V_QUANHEPHAPLUAT_NAME=>NULL,--TL.QUANHEPHAPLUAT_NAME,
            V_PT_RUTKINHNGHIEM=>NULL
		)
		BULK COLLECT INTO v_ARRAY
        FROM (
                SELECT TL.*
                FROM AHC_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')

                UNION 
                SELECT TL.*
                FROM AHC_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND 
                    (NOT EXISTS (SELECT  STQD.* FROM AHC_SOTHAM_QUYETDINH STQD 
                        INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 WHERE TL.DONID = STQD.DONID)
                    AND NOT EXISTS (SELECT BA.* FROM AHC_SOTHAM_BANAN BA WHERE TL.DONID = BA.DONID))

                UNION 
                SELECT TL.*
                FROM AHC_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND  
                    (EXISTS (SELECT  STQD.* FROM AHC_SOTHAM_QUYETDINH STQD 
                        INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 
                        WHERE TL.DONID = STQD.DONID AND STQD.NGAYQD BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')
                        )
                    OR EXISTS (SELECT BA.* FROM AHC_SOTHAM_BANAN BA 
                               WHERE TL.DONID = BA.DONID AND BA.NGAYTUYENAN BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')))
            ) TL;
            FILL_HANHCHINH_SOTHAM(v_ARRAY);
            
		OPEN curReturn FOR SELECT * FROM TABLE(v_ARRAY)
        ORDER by EXTRACT(YEAR FROM  V_NGAYTHULY),to_number(REGEXP_REPLACE(V_SOTHULY, '[^0-9]')),V_NGAYTHULY;
		
--	EXCEPTION 
--		WHEN OTHERS THEN 
--			RAISE_APPLICATION_ERROR(-20000, sqlerrm);
	END;
    /*2 - SỔ THỤ LÝ VÀ KẾT QỦA GIẢI QUYẾT CÁC VỤ ÁN HÀNH CHÍNH SƠ THẨM*/
	PROCEDURE FILL_HANHCHINH_SOTHAM
	(
		v_ARRAY IN OUT T_HANHCHINH_SOTHAM
	) AS
        COLUMN_5 CLOB;

        COLUMN_6_CHECK NUMBER;
        COLUMN_6 VARCHAR(4000);
        COLUMN_11 CLOB;
	BEGIN	
		--v_ARRAY:=T_HANHCHINH_SOTHAM();
		-- v_TL_1 - THỤ LÝ Số, ngày tháng năm - 1 - 

		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				T2.QUANHEPHAPLUATID v_QUANHEPHAPLUATID,
				T2.SOTHULY || CHR(10) || TO_CHAR(T2.NGAYTHULY,'DD/MM/YYYY') v_TL_1,
                T2.NGAYTHULY  V_NGAYTHULY,T2.SOTHULY V_SOTHULY
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHC_SOTHAM_THULY T2 ON T1.v_THULYID=T2.ID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_TL_1:=ITEM.v_TL_1;
			v_ARRAY(ITEM.v_STT).v_QUANHEPHAPLUATID:=ITEM.v_QUANHEPHAPLUATID;
            v_ARRAY(ITEM.v_STT).V_NGAYTHULY:=ITEM.V_NGAYTHULY;v_ARRAY(ITEM.v_STT).V_SOTHULY:=ITEM.V_SOTHULY;
		END LOOP;
		-- v_NGUOIKK_2 - NGƯỜI KHỞI KIỆN Họ tên, địa chỉ Họ tên người đại diện, chức vụ, địa chỉ - 2 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU || '; ' ||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
            DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) V_NGUOIKK_2
			FROM 
				TABLE(v_ARRAY) T1 
				 INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI 
                 FROM AHC_DON_DUONGSU ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='NGUYENDON' --NGUYÊN ĐƠN
                 LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                 LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID  
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).V_NGUOIKK_2:=ITEM.V_NGUOIKK_2;
		END LOOP;

		-- v_NGUOIBKK_3 - NGƯỜI BỊ KHỞI KIỆN Họ tên, địa chỉ Họ tên người đại diện, chức vụ, địa chỉ - 3 - 
        FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU || '; ' ||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
            DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_NGUOIBKK_3
			FROM 
				TABLE(v_ARRAY) T1 
				 INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI 
                 FROM AHC_DON_DUONGSU ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='BIDON' --NGUYÊN ĐƠN
                 LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                 LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID  
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_NGUOIBKK_3:=ITEM.v_NGUOIBKK_3;
		END LOOP;
		-- v_NGUOI_QLNVLQ_4 - NGƯỜI CÓ QUYỀN LỢI, NGHĨA VỤ LIÊN QUAN Họ tên, địa chỉ Họ tên người đại diện, chức vụ, địa chỉ - 4 - 
        FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU || '; ' ||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
            DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_NGUOI_QLNVLQ_4
			FROM 
				TABLE(v_ARRAY) T1 
				 INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI 
                 FROM AHC_DON_DUONGSU ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='QUYENNVLQ' --NGUYÊN ĐƠN
                 LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                 LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID  
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_NGUOI_QLNVLQ_4:=ITEM.v_NGUOI_QLNVLQ_4;
		END LOOP;

		-- v_NGUOIBV_QLIHP_DS_5 - NGƯỜI BẢO VỆ QUYỀN, LỢI ÍCH HỢP PHÁP CỦA ĐƯƠNG SỰ -- Họ tên, chức danh (nếu là Luật sư) - 5 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, T1.v_VUANID 
			FROM TABLE(v_ARRAY) T1 
		) LOOP

            COLUMN_5 := '';

            FOR ITEMS IN (SELECT * 
                          FROM AKT_DON_THAMGIATOTUNG T2
                          WHERE T2.TUCACHTGTTID like 'TGTTDS%' AND ITEM.v_VUANID = T2.DONID)
            LOOP

                IF(ITEMS.TUCACHTGTTID LIKE 'TGTTDS_02') -- Luật sư
                            THEN COLUMN_5 := COLUMN_5 || '- ' || ITEMS.HOTEN||'; ' || ITEMS.TEN_VPLS || '; '|| ITEMS.DIACHI || ';'|| CHR(10);
                    ELSE 
                        COLUMN_5 := COLUMN_5 || '- ' || ITEMS.HOTEN||'; ' || NVL(ITEMS.HKTTCHITIET, ITEMS.TAMTRUCHITIET) || ';' || CHR(10) ;
                END IF;

            END LOOP;

			v_ARRAY(ITEM.v_STT).v_NGUOIBV_QLIHP_DS_5 := COLUMN_5;

		END LOOP; 

		-- v_QHPL_6 - QUAN HỆ PHÁP LUẬT - 6 - 
        FOR ITEM IN (
			SELECT 
				T1.v_STT, T1.V_VUANID
			FROM 
				TABLE(v_ARRAY) T1
		) LOOP
                COLUMN_6_CHECK := 0;
                COLUMN_6 := '';

                SELECT CASE WHEN EXISTS (SELECT 1 FROM AHC_SOTHAM_BANAN WHERE DONID = ITEM.V_VUANID) 
                            THEN 1
                            ELSE 0 
                        END INTO COLUMN_6_CHECK
                FROM DUAL;                

                IF(COLUMN_6_CHECK = 1) THEN
                    SELECT DECODE(NVL(T1.QUANHEPHAPLUAT_NAME,''), '', T2.CASE_NAME,T1.QUANHEPHAPLUAT_NAME) INTO COLUMN_6
                    FROM AHC_SOTHAM_BANAN T1 
                        LEFT JOIN DM_QHPL_TK T2 ON T1.QHPLTKID=T2.ID
                     WHERE T1.DONID = ITEM.V_VUANID;
                ELSE 

                    SELECT CASE WHEN EXISTS (SELECT 1 FROM AHC_SOTHAM_QUYETDINH QD
                                             INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = QD.QUYETDINHID AND DMQD.KET_THUC = 1
                                             WHERE QD.DONID = ITEM.V_VUANID) 
                                THEN 1
                                ELSE 0 
                            END INTO COLUMN_6_CHECK
                    FROM DUAL; 

                   IF(COLUMN_6_CHECK = 1) THEN

                        SELECT DECODE(NVL(T1.QUANHEPHAPLUAT,''), '', T2.CASE_NAME,T1.QUANHEPHAPLUAT) 
                        INTO COLUMN_6
                        FROM AHC_SOTHAM_QUYETDINH T1
                            INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = T1.QUYETDINHID AND DMQD.KET_THUC = 1
                            LEFT JOIN DM_QHPL_TK T2 ON T2.ID = T1.QHPLTKID
                        WHERE T1.DONID = ITEM.V_VUANID;

                   ELSE

                        SELECT CASE WHEN EXISTS (SELECT 1 FROM AHC_SOTHAM_THULY WHERE DONID = ITEM.V_VUANID) 
                                    THEN 1
                                    ELSE 0 
                                END INTO COLUMN_6_CHECK
                        FROM DUAL;

                        IF(COLUMN_6_CHECK = 1) THEN

                            SELECT DECODE(NVL(T1.QUANHEPHAPLUAT_NAME,''), '', T2.CASE_NAME,T1.QUANHEPHAPLUAT_NAME) INTO COLUMN_6
                            FROM AHC_SOTHAM_THULY T1 
                                LEFT JOIN DM_QHPL_TK T2 ON T1.QHPLTKID=T2.ID
                             WHERE T1.DONID = ITEM.V_VUANID;
                        END IF;
                   END IF; 
                END IF;       

                v_ARRAY(ITEM.v_STT).v_QHPL_6:= COLUMN_6;

		END LOOP;      

		-- v_ADBPKCTT_7 - ÁP DỤNG BIỆN PHÁP KHẨN CẤP TẠM THỜI Số, ngày tháng năm - 7 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOQD || CHR(10) ||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_ADBPKCTT_7
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHC_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_LOAI T3 on T3.ID=T2.LOAIQDID and T3.MA='ADBPTT'
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_ADBPKCTT_7:=ITEM.v_ADBPKCTT_7;
		END LOOP;
--		-- v_CHUYENHS_VA_8 - CHUYỂN HỒ SƠ VỤ ÁN Số, ngày tháng năm và nơi nhận - 8 - 
        FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
						T2.SOQD||CHR(10)||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY') ||CHR(10)|| TA.MA_TEN
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_CHUYENHS_VA_8
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHC_SOTHAM_QUYETDINH T2 
                LEFT JOIN DM_QD_QUYETDINH QD ON T2.QUYETDINHID=QD.ID ON T1.v_VUANID=T2.DONID 
                LEFT JOIN AHC_CHUYEN_NHAN_AN CN ON CN.VUANID=T2.DONID
                LEFT JOIN DM_TOAAN TA ON TA.ID=CN.TOANHANID
                WHERE QD.ID=4 -- QD.ID=4 Quyết định chuyển vụ án vì không thuộc thẩm quyền
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_CHUYENHS_VA_8:=ITEM.v_CHUYENHS_VA_8;
		END LOOP;
		-- v_TDC_9 - TẠM ĐÌNH CHỈ Số, ngày tháng năm - 9 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOQD || CHR(10) ||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_TDC_9
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHC_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_LOAI T3 on T3.ID=T2.LOAIQDID and T3.MA='TDC'
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_TDC_9:=ITEM.v_TDC_9;
		END LOOP;

		-- v_DC_10 - ĐÌNH CHỈ Số, ngày tháng năm - 10 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOQD || CHR(10) ||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_DC_10
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHC_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_LOAI T3 on T3.ID=T2.LOAIQDID and T3.MA='DC'
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_DC_10:=ITEM.v_DC_10;
		END LOOP;

		-- v_LYDO_11 - LÝ DO - 11 -
		FOR ITEM IN (
			SELECT 
				T1.v_STT, T1.V_VUANID
			FROM 
				TABLE(v_ARRAY) T1 
		) LOOP
            COLUMN_11 := '';
            FOR ITEMS IN (SELECT DONID, REGEXP_REPLACE(DMQD.TEN, '^\d+-[A-Za-z]+\. Quyết định ', '') AS TENQD 
                                      ,-- DECODE(NVL(DMLD.TEN,''),'','Lý do: ' || T2.LYDO_NAME, 'Lý do: ' || DMLD.TEN) 
                                       DECODE(DMLD.TEN, NULL, '', 'Lý do: ' || DMLD.TEN) LYDO
                            FROM AHC_SOTHAM_QUYETDINH T2
                                INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = T2.QUYETDINHID
                                LEFT JOIN DM_QD_QUYETDINH_LYDO DMLD ON DMLD.ID = T2.LYDOID
                            WHERE (DMQD.TEN LIKE '%đình chỉ%' or DMQD.TEN like '%biện pháp%') AND T2.DONID = ITEM.v_VUANID
                        )
            LOOP
                 COLUMN_11 := COLUMN_11 || '- QĐ ' || ITEMS.TENQD || '. ' ||  ITEMS.LYDO || CHR(10);
            END LOOP;

                v_ARRAY(ITEM.v_STT).v_LYDO_11 := COLUMN_11;

		END LOOP;

		-- v_HDXX_VKS_TKPT_12 - HỘI ĐỒNG XÉT XỬ, ĐẠI DIỆN VIỆN KIỂM SÁT, THƯ KÝ PHIÊN TOÀ -- Ghi đầy đủ họ tên - 12 - 
        FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || NVL(T3.HOTEN,'')||NVL(T4.HOTEN,'')||
						' ('||DECODE(T2.MAVAITRO,'HTND','HTND','KSV','KSV','THAMPHAN','TPCT','THAMPHANDUKHUYET','TPDK','THAMPHANHDXX','TPTV','THUKY','TK','THUKYDUKHUYET','TKDK','')||')'
						AS VARCHAR2(4000)
					), CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_HDXX_VKS_TKPT_12
			FROM 
				TABLE(v_ARRAY) T1
                INNER JOIN ( select tp.* from AHC_SOTHAM_HDXX tp where tp.MAVAITRO!='THAMPHAN' --loại thẩm phán ra khỏi danh sách
                              union all
                              select tp.* from AHC_SOTHAM_HDXX tp
                                WHERE tp.MAVAITRO='THAMPHAN' --xử lý, lấy 1 thẩm phán mới nhất
                                and EXISTS(SELECT 'X' FROM (
                                                    SELECT TT.DONID,TT.ID FROM (  
                                                     SELECT DONID,FIRST_VALUE(CANBOID) OVER (PARTITION BY DONID ORDER BY NGAYTAO DESC) ID
                                                     FROM  AHC_SOTHAM_HDXX WHERE MAVAITRO='THAMPHAN'
                                                        )TT GROUP BY TT.DONID,TT.ID
                                                 )XX WHERE XX.ID=TP.CANBOID AND XX.DONID=TP.DONID
                                             )
                         ) T2 on T1.v_VUANID=T2.DONID
				LEFT JOIN DM_CANBO T3 ON T3.ID=T2.CANBOID AND INSTR('THAMPHAN,THAMPHANHDXX,THAMPHANDUKHUYET,THUKY,THUKYDUKHUYET,HTND',T2.MAVAITRO)>0
				LEFT JOIN DM_CANBOVKS T4 ON T4.ID=T2.CANBOID AND INSTR('HTND,KSV',T2.MAVAITRO)>0
        group by T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_HDXX_VKS_TKPT_12:=ITEM.v_HDXX_VKS_TKPT_12;
		END LOOP;
		-- v_BA_ST_13 - BẢN ÁN SƠ THẨM Số, ngày tháng năm - 13 - 
		FOR ITEM IN (
            SELECT T1.v_STT, LISTAGG( T2.SOBANAN || CHR(10) || TO_CHAR(T2.NGAYTUYENAN,'DD/MM/YYYY'),CHR(10) ) WITHIN GROUP (ORDER BY T1.v_STT) v_BA_ST_13
            FROM 
                TABLE(v_ARRAY) T1
                INNER JOIN AHC_SOTHAM_BANAN T2 ON T1.v_VUANID = T2.DONID
            GROUP BY T1.v_STT

            UNION ALL

            SELECT 
                T1.v_STT, LISTAGG(T2.SOQD || CHR(10) || TO_CHAR(T2.NGAYQD,'DD/MM/YYYY'),CHR(10)) WITHIN GROUP (ORDER BY T1.v_STT) v_BA_ST_13
            FROM 
                TABLE(v_ARRAY) T1
                INNER JOIN AHC_SOTHAM_QUYETDINH T2 ON T1.v_VUANID = T2.DONID
                INNER JOIN DM_QD_QUYETDINH QD ON T2.QUYETDINHID = QD.ID AND KET_THUC = 1
            --WHERE T2.ISCONGBOQD = 1
            GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_BA_ST_13:= v_ARRAY(ITEM.v_STT).v_BA_ST_13 ||ITEM.v_BA_ST_13;

		END LOOP;

        -- v_TTND_BA_QD_TA_ST_14 - TÓM TẮT NỘI DUNG BẢN ÁN, QUYẾT ĐỊNH CỦA TOÀ ÁN CẤP SƠ THẨM
	FOR ITEM IN (
			SELECT 
				T1.v_STT, T1.v_VUANID, 
				T2.NOIDUNG v_TTND_BA_QD_TA_ST_14
			FROM 
				TABLE(v_ARRAY) T1 
                INNER JOIN AHC_SOTHAM_BANAN T2 ON T1.v_VUANID=T2.DONID
				LEFT JOIN DM_DATAITEM T3 ON T3.ID=T2.QUANHEPHAPLUATID

            union

            SELECT 
				T1.v_STT, T1.v_VUANID, 
				LISTAGG(T2.NOIDUNG, CHR(10)) WITHIN GROUP (ORDER BY T2.NGAYQD) v_TTND_BA_QD_TA_ST_14
			FROM 
				TABLE(v_ARRAY) T1 
                INNER JOIN AHC_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
                INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = T2.QUYETDINHID AND DMQD.KET_THUC = 1
            GROUP BY T1.v_STT, T1.v_VUANID
		) LOOP

			v_ARRAY(ITEM.v_STT).v_TTND_BA_QD_TA_ST_14:= v_ARRAY(ITEM.v_STT).v_TTND_BA_QD_TA_ST_14 || ITEM.v_TTND_BA_QD_TA_ST_14;

		END LOOP;      


		-- v_KN_CQNN_XXTN_15 - KIẾN NGHỊ VỚI CƠ QUAN NHÀ NƯỚC, NGƯỜI ĐỨNG ĐẦU CƠ QUAN NHÀ NƯỚC XEM XÉT TRÁCH NHIỆM CỦA CƠ QUAN NHÀ NƯỚC, NGƯỜI CÓ THẨM QUYỀN CỦA CƠ QUAN NHÀ NƯỚC - 15 - 
        for item in (select T1.v_STT, T1.v_VUANID,
                            decode(T2.TK_ISKIENCOQUANNN,1,'X','') v_KN_CQNN_XXTN_15, T2.NOIDUNG v_TTND_BA_QD_TA_ST_14
                     from table(v_ARRAY) T1
                        INNER join AHC_SOTHAM_BANAN T2 ON T1.v_VUANID=T2.DONID
        ) 
        loop

            v_ARRAY(ITEM.v_STT).v_KN_CQNN_XXTN_15:=ITEM.v_KN_CQNN_XXTN_15;
        END LOOP;

