	PROCEDURE FILL_PHASAN_SOTHAM
	(
		v_ARRAY IN OUT T_PHASAN_SOTHAM
	) AS
	BEGIN	
		--v_ARRAY:=T_PHASAN_SOTHAM();
		-- v_NGAYNHANDON_1 - NGÀY NHẬN ĐƠN - 1
		for item in
    (
      select
        T1.v_STT,
        LISTAGG(
          to_char(T2.NGAYNHANDON,'dd/MM/yyyy')
          ,CHR(10)
        )within group (order by T1.v_STT)  v_NGAYNHANDON_1
      from table(v_ARRAY) T1
      inner join APS_DON T2 on T1.v_VUANID=T2.ID
      group by T1.v_STT
    ) loop
      v_ARRAY(item.v_STT).v_NGAYNHANDON_1 := item.v_NGAYNHANDON_1;
    end loop;
    -- v_NGUOINOPDON_2 - NGƯỜI NỘP ĐƠN  -- Họ tên, địa chỉ, tư cách pháp lý (Điều 5) - 2
		for item in
    (
      select
        T1.v_STT,
        LISTAGG(
          cast(
                '- ' || T2.TENDUONGSU || '; ' ||
                nvl2(T2.TAMTRUCHITIET,T2.TAMTRUCHITIET || '; ','') ||
                'tư cách pháp lý: ' || T3.TEN
               as varchar2(4000)
               )
          ,CHR(10)
        )within group (order by T1.v_STT)  v_NGUOINOPDON_2
      from table(v_ARRAY) T1
      inner join APS_DON_DUONGSU T2 on T1.v_VUANID=T2.DONID and T2.ISDAIDIEN=1 and T2.TUCACHTOTUNG_MA='NGUYENDON'
      inner join DM_DATAITEM T3 on T3.ID=T2.LOAIDUONGSU
      group by T1.v_STT
    ) loop
      v_ARRAY(item.v_STT).v_NGUOINOPDON_2 := item.v_NGUOINOPDON_2;
    end loop;
    -- v_DN_HTX_BI_YCTBPS_3 - DOANH NGHIỆP, HỢP TÁC XÃ BỊ YÊU CẦU TUYÊN BỐ PHÁ SẢN  -- Tên, địa chỉ, người đại diện, ngày thành lập, loại hình doanh nghiệp, doanh nghiệp có vốn nhà nước, có vốn đầu tư nước ngoài, niêm yết, tổ chức tín dụng - 3
		for item in
    (
      select
        T1.v_STT,
        LISTAGG(
          cast(
              T2.TENDUONGSU || '; ' ||
              nvl2(T2.NDD_DIACHICHITIET,T2.NDD_DIACHICHITIET || '; ','') ||
              nvl2(T2.NGUOIDAIDIEN,'Người đại diện: '|| T2.NGUOIDAIDIEN || '; ','') ||
              'tư cách pháp lý: ' || T3.CASE_NAME
              as varchar2(4000)
              )
          ,CHR(10)
        )within group (order by T1.v_STT)  v_DN_HTX_BI_YCTBPS_3
      from table(v_ARRAY) T1
      inner join APS_DON_DUONGSU T2 on T1.v_VUANID=T2.DONID and T2.ISDAIDIEN=1 and T2.TUCACHTOTUNG_MA='BIDON'
      inner join DM_QHPL_TK T3 on T3.ID=T2.LOAIDUONGSU and T3.STYLES=5 -- ENUM_QHPLTK.PHASAN=5
      group by T1.v_STT
    ) loop
      v_ARRAY(item.v_STT).v_DN_HTX_BI_YCTBPS_3 := item.v_DN_HTX_BI_YCTBPS_3;
    end loop;
    -- v_MANGANHCHINH_4 - MÃ NGÀNH CHÍNH - 4
		for item in
    (
      select
        T1.v_STT,
        REGEXP_SUBSTR (T3.CASE_NAME, '\d+') v_MANGANHCHINH_4
      from table(v_ARRAY) T1
      inner join APS_DON_DUONGSU T2 on T1.v_VUANID=T2.DONID and T2.ISDAIDIEN=1 and T2.TUCACHTOTUNG_MA='BIDON'
      inner join DM_QHPL_TK T3 on T3.ID=T2.NGANHKINHTEID and T3.STYLES=15 -- ENUM_QHPLTK.NGANHKINHTE=15
    ) loop
      v_ARRAY(item.v_STT).v_MANGANHCHINH_4 := item.v_MANGANHCHINH_4;
    end loop;
    -- v_THAMPHAN_PCGQ_5 - HỌ VÀ TÊN THẨM PHÁN ĐƯỢC PHÂN CÔNG GIẢI QUYẾT - 5
		for item in
    (
      select
        T1.v_STT,
        nvl(T3.HOTEN,'') v_THAMPHAN_PCGQ_5
      from table(v_ARRAY) T1
      inner join APS_DON_THAMPHAN T2 on T2.DONID=T1.v_VUANID
      inner join DM_CANBO T3 on T3.ID=T2.CANBOID
    ) loop
      v_ARRAY(item.v_STT).v_THAMPHAN_PCGQ_5 := item.v_THAMPHAN_PCGQ_5;
    end loop;
    -- v_XLD_CHUYENDONCHOTAKHAC_6 - XỬ LÝ ĐƠN YÊU CẦU MỞ THỦ TỤC PHÁ SẢN - CHUYỂN ĐƠN CHO TÒA ÁN KHÁC --  Số, ngày tháng năm - 6
		for item in
    (
      select
        T1.v_STT,
        to_char(T2.NGAYGQ_YC,'dd/MM/yyyy') v_XLD_CHUYENDONCHOTAKHAC_6
      from table(v_ARRAY) T1
      inner join APS_DON_XULY T2 on T2.DONID=T1.v_VUANID and T2.LOAIGIAIQUYET=1--ENUM_APS_BIENPHAPGQ.ADS_ChuyenDonTrongNganh=1
    ) loop
