    -- v_DNKN_LENTACAPTREN_36 - ĐỀ NGHỊ, KHÁNG NGHỊ CÁC QUYẾT ĐỊNH LÊN TÒA ÁN CẤP TRÊN -- Ngày, tháng, năm, loại quyết định - 36
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
                T4.KhangCao || CHR(10) || T7.KhangNghi
                ,CHR(10)
              ) within group (order by T1.v_STT) v_DNKN_LENTACAPTREN_36
			FROM 
				TABLE(v_ARRAY) T1 
				left JOIN (select T2.DONID,
                      cast (to_char(T2.NGAYKHANGCAO,'dd/MM/yyyy') || CHR(10) || 
                            T6.TEN || '; ' as varchar(4000)) KhangCao
                    from APS_SOTHAM_KHANGCAO T2
                    inner join APS_SOTHAM_QUYETDINH T5 on T2.DONID=T5.DONID and T5.ID=T2.SOQDBA
                    inner join DM_QD_QUYETDINH T6 on T6.ID=T5.QUYETDINHID
                    where T2.LOAIKHANGCAO=1
                    ) T4 ON T1.v_VUANID=T4.DONID
        left JOIN (select T2.DONID,
                      cast (to_char(T2.NGAYKN,'dd/MM/yyyy') || CHR(10) || 
                            T6.TEN || '; ' as varchar(4000)) KhangNghi
                    from APS_SOTHAM_KHANGNGHI T2
                    inner join APS_SOTHAM_QUYETDINH T5 on T2.DONID=T5.DONID and T5.ID=T2.BANANID
                    inner join DM_QD_QUYETDINH T6 on T6.ID=T5.QUYETDINHID
                    where T2.LOAIKN=1
                  ) T7 ON T1.v_VUANID=T7.DONID
        GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_DNKN_LENTACAPTREN_36:=ITEM.v_DNKN_LENTACAPTREN_36;
		END LOOP;
    -- v_CHUYENHS_TA_CAPTREN_37 - CHUYỂN HỒ SƠ CHO TÒA ÁN CẤP TRÊN -- Ngày, tháng, năm - 37
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					TO_CHAR(T2.NGAYGIAO,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT)  v_CHUYENHS_TA_CAPTREN_37
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN APS_CHUYEN_NHAN_AN T2 ON T1.v_VUANID=T2.VUANID
			GROUP BY T1.v_STT				
		) LOOP
			v_ARRAY(ITEM.v_STT).v_CHUYENHS_TA_CAPTREN_37:=ITEM.v_CHUYENHS_TA_CAPTREN_37;
		END LOOP;
    -- v_QDGQ_DNKN_TA_CAPTREN_38 - QUYẾT ĐỊNH GIẢI QUYẾT ĐỀ NGHỊ, KHÁNG NGHỊ CỦA TÒA ÁN CẤP TRÊN  -- Số, ngày tháng năm; kết quả - 38

    -- v_QUAHANLUATDINH_39 - QUÁ HẠN LUẬT ĐỊNH --  - 39
		for item in
    (
      select
        T1.v_STT,
        decode(T2.TK_ISQUAHAN,1,'X','') v_QUAHANLUATDINH_39
      from table(v_ARRAY) T1
      inner join APS_SOTHAM_BANAN T2 on T2.DONID=T1.v_VUANID
    ) loop
      v_ARRAY(item.v_STT).v_QUAHANLUATDINH_39 := item.v_QUAHANLUATDINH_39;
    end loop;
    -- v_GHICHU_40 - GHI CHÚ - 40
	END;
END PKG_GSTP_SOTHULY_SOTHAM;

