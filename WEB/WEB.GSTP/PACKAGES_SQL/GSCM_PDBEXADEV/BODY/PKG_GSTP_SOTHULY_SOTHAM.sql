                EXCEPTION WHEN NO_DATA_FOUND THEN COLUMN_25 := ' ';
                END; 
            END IF;

            IF(COLUMN_25 LIKE ' ') THEN
                BEGIN
                        SELECT DECODE(T2.OPTIONS,1,'X','') INTO COLUMN_25
                        FROM AHN_SOTHAM_QUYETDINH T1
                            INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = T1.QUYETDINHID  AND DMQD.KET_THUC = 1
                            LEFT JOIN DM_QHPL_TK T2 ON T2.ID = T1.QHPLTKID
                        WHERE T1.DONID = ITEM.V_VUANID
                        ORDER BY T1.ID DESC FETCH FIRST ROW ONLY;

                EXCEPTION WHEN NO_DATA_FOUND THEN COLUMN_25 := ' '; 
                END; 
            END IF;     

            IF(COLUMN_25 LIKE ' ') THEN
                BEGIN   
                        SELECT DECODE(T2.OPTIONS,1,'X','')  INTO COLUMN_25
                        FROM AHN_SOTHAM_THULY T1 
                            LEFT JOIN DM_QHPL_TK T2 ON T1.QHPLTKID=T2.ID
                        WHERE T1.DONID = ITEM.V_VUANID
                        ORDER BY T1.ID DESC FETCH FIRST ROW ONLY;
                EXCEPTION WHEN NO_DATA_FOUND THEN COLUMN_25 := ' ';
                END;  
