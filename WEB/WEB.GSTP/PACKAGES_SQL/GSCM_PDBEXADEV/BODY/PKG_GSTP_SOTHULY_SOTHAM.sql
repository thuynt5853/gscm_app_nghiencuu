  CREATE OR REPLACE NONEDITIONABLE PACKAGE BODY "GSCM"."PKG_GSTP_SOTHULY_SOTHAM" AS
PROCEDURE SO_DANSU_SOTHAM
	(
		 in_TOAANID IN NUMBER,
		 in_TOAANCAPCON IN NVARCHAR2,
		 in_NGAYBATDAU IN NVARCHAR2,
		 in_NGAYKETTHUC IN NVARCHAR2,
		 curReturn OUT SYS_REFCURSOR
	) AS
		v_ARRAY T_DANSU_SOTHAM;
		v_IDS T_ID;
		--ITEM R_DANSU_SOTHAM;
	BEGIN	
		--
		--TÒA ÁN CẤP CON
		v_IDS:=T_ID();
		IF (in_TOAANCAPCON='TRUE') THEN
			SELECT R_ID(ID) BULK COLLECT INTO v_IDS FROM DM_TOAAN WHERE CAPCHAID=in_TOAANID;
		END IF;
		v_IDS.EXTEND();
		v_IDS(v_IDS.COUNT):=R_ID(in_TOAANID);

    SELECT R_DANSU_SOTHAM(
			v_STT=>row_number() over (order by TL.ID),
			v_THULYID=>TL.ID,
			v_VUANID=>TL.DONID,
			v_TOAANID=>TL.TOAANID,
			v_QUANHEPHAPLUATID=>NULL,
			v_TL_1=>NULL,
			v_ND_NYC_2=>NULL,
			v_BD_NLQ_DS_3=>NULL,
			v_DKK_CQTC_4=>NULL,
			v_NGUOI_QLNVLQ_5=>NULL,
			v_NGUOIBV_QLIHP_DS_6=>NULL,
			v_QHPLKHITL_7=>NULL,
			v_ADBPKCTT_8=>NULL,
			v_CHUYENHS_VUVIEC_9=>NULL,
			v_TDC_10=>NULL,
			v_DC_11=>NULL,
			v_LYDO_12=>NULL,
			v_CONGNHAN_THOATHUAN_DS_13=>NULL,
			v_HDXX_VKS_TKPT_14=>NULL,
			v_BA_QDST_15=>NULL,
			v_QHPLMATAGQ_16=>NULL,
			v_TTND_BA_QD_TA_ST_17=>NULL,
			v_KQGQYC_HUYQDCABIET_18=>NULL,
			v_XETXULUUDONG_19=>NULL,
			v_APDUNGANLE_20=>NULL,
			v_GQ_TTRG_21=>NULL,
			v_COYEUTONUOCNGOAI_22=>NULL,
			v_VIECDS_23=>NULL,
			v_KC_24=>NULL,
			v_KN_25=>NULL,
			v_CHUYENHS_TA_PT_26=>NULL,
			v_QD_TA_PT_27=>NULL,
			v_GHICHU_28=>NULL,
            V_NGAYTHULY=>NULL,
            V_SOTHULY=>NULL,
            V_QUANHEPHAPLUAT_NAME=>TL.QUANHEPHAPLUAT_NAME,
            V_PT_RUTKINHNGHIEM=>NULL
		) 
--		BULK COLLECT INTO v_ARRAY
--		FROM ADS_SOTHAM_THULY TL 
--            INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
--		WHERE
--			NGAYTHULY BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY');
		BULK COLLECT INTO v_ARRAY
        FROM (  SELECT TL.*
                FROM ADS_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')

                UNION 
                SELECT TL.*
                FROM ADS_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND 
                    (NOT EXISTS (SELECT  STQD.* FROM ADS_SOTHAM_QUYETDINH STQD 
                        INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 WHERE TL.DONID = STQD.DONID)
                    AND NOT EXISTS (SELECT BA.* FROM ADS_SOTHAM_BANAN BA WHERE TL.DONID = BA.DONID))

                UNION 
                SELECT TL.*
                FROM ADS_SOTHAM_THULY TL 
                    INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
                WHERE
                    NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND  
                    (EXISTS (SELECT  STQD.* FROM ADS_SOTHAM_QUYETDINH STQD 
                        INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 
                        WHERE TL.DONID = STQD.DONID AND STQD.NGAYQD BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')
                        )
                    OR EXISTS (SELECT BA.* FROM ADS_SOTHAM_BANAN BA 
                               WHERE TL.DONID = BA.DONID AND BA.NGAYTUYENAN BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')))
            ) TL;


		--
		--THONG TIN SO THU LY
		FILL_DANSU_SOTHAM(v_ARRAY);

		OPEN curReturn FOR SELECT * FROM TABLE(v_ARRAY) --ORDER BY  REGEXP_REPLACE(V_SOTHULY, '[^0-9]'),V_NGAYTHULY;
        ORDER by EXTRACT(YEAR FROM  V_NGAYTHULY),to_number(REGEXP_REPLACE(V_SOTHULY, '[^0-9]')),V_NGAYTHULY;

	EXCEPTION 
		WHEN OTHERS THEN 
			RAISE_APPLICATION_ERROR(-20000, sqlerrm);
	END;
 /*15 - SỔ THỤ LÝ VÀ KẾT QỦA GIẢI QUYẾT CÁC VỤ VIỆC DÂN SỰ SƠ THẨM*/
	PROCEDURE FILL_DANSU_SOTHAM
	(
		v_ARRAY IN OUT T_DANSU_SOTHAM
	) AS
        COLUMN_5 CLOB;
        COLUMN_6 CLOB;

        COLUMN_12 CLOB;
        COLUMN_23 VARCHAR(10);
	BEGIN	
		--v_ARRAY:=T_DANSU_SOTHAM();
		-- v_TL_1 - THỤ LÝ Số, ngày tháng năm - 1 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				T2.QUANHEPHAPLUATID v_QUANHEPHAPLUATID,
				T2.SOTHULY || CHR(10) || TO_CHAR(T2.NGAYTHULY,'DD/MM/YYYY') v_TL_1,
                T2.NGAYTHULY  V_NGAYTHULY,T2.SOTHULY V_SOTHULY --anhvh add de dung cho order by 24/03/2023
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_THULY T2 ON T1.v_THULYID=T2.ID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_TL_1:=ITEM.v_TL_1;
			v_ARRAY(ITEM.v_STT).v_QUANHEPHAPLUATID:=ITEM.v_QUANHEPHAPLUATID;
            v_ARRAY(ITEM.v_STT).V_NGAYTHULY:=ITEM.V_NGAYTHULY;v_ARRAY(ITEM.v_STT).V_SOTHULY:=ITEM.V_SOTHULY;
		END LOOP;
		-- v_ND_NYC_2 - NGUYÊN ĐƠN HOẶC NGƯỜI YÊU CẦU Họ tên, năm sinh, địa chỉ - 2 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU || '; ' ||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
                        DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_ND_NYC_2
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI  
                            FROM ADS_DON_DUONGSU
                            ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='NGUYENDON' --NGUYÊN ĐƠN
                LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_ND_NYC_2:=ITEM.v_ND_NYC_2;
		END LOOP;

		-- v_BD_NLQ_DS_3 - BỊ ĐƠN HOẶC NGƯỜI LIÊN QUAN TRONG VIỆC DÂN SỰ Họ tên, năm sinh, địa chỉ - 3 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU||';'||
						case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end ||
						 DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ')||DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN 
						AS VARCHAR2(4000)
					),CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_BD_NLQ_DS_3
			FROM 
				TABLE(v_ARRAY) T1 
                    INNER JOIN (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI  
                        FROM ADS_DON_DUONGSU
                        ) T2 ON T1.v_VUANID=T2.DONID AND T2.TUCACHTOTUNG_MA ='BIDON' --BỊ ĐƠN
                   LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                   LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID   
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_BD_NLQ_DS_3:=ITEM.v_BD_NLQ_DS_3;
		END LOOP;

		-- v_DKK_CQTC_4 - ĐƠN KHỞI KIỆN CỦA CƠ QUAN, TỔ CHỨC - 4 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(MAX(T2.LOAIDUONGSU),2,'Cơ quan',3,'Tổ chức','') v_DKK_CQTC_4
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_DON_DUONGSU T2 ON T2.ISDAIDIEN=1 AND T1.v_VUANID=T2.DONID
        GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_DKK_CQTC_4:=ITEM.v_DKK_CQTC_4;
		END LOOP;


		FOR ITEM IN (
			SELECT 
				T1.v_STT, T1.v_VUANID 
			FROM TABLE(v_ARRAY) T1 
		) LOOP


            -- v_NGUOI_QLNVLQ_5 - NGƯỜI CÓ QUYỀN LỢI, NGHĨA VỤ LIÊN QUAN Họ tên, năm sinh, địa chỉ - 5 - 
            COLUMN_5 := '';
            FOR ITEM_GROUP IN (SELECT   '- ' || T2.TENDUONGSU ||'; ' AS TENDUONGSU,
                                        case when T2.NAMSINH = 0 then ' ' else ' ' || T2.NAMSINH ||'; ' end AS NAMSINH,
                                        DECODE(T2.DIACHI,NULL,NULL,T2.DIACHI||', ') as DIACHI,
                                        DECODE(H.TEN,NULL,NULL,H.TEN||', ')|| TI.TEN AS TEN
                               FROM (SELECT DONID,TENDUONGSU,NAMSINH,TUCACHTOTUNG_MA,TAMTRUTINHID,TAMTRUID,DECODE(LOAIDUONGSU,1,TAMTRUCHITIET,NDD_DIACHICHITIET) as DIACHI  
                                       FROM ADS_DON_DUONGSU T2
                                       WHERE ITEM.v_VUANID = T2.DONID AND T2.TUCACHTOTUNG_MA='QUYENNVLQ' --NGƯỜI CÓ QUYỀN LỢI NGHĨA VỤ LIÊN QUAN
                                    ) T2

                                           LEFT JOIN DM_HANHCHINH TI ON TI.ID=T2.TAMTRUTINHID 
                                           LEFT JOIN DM_HANHCHINH H ON H.ID=T2.TAMTRUID 
                               )
            LOOP 
                COLUMN_5 := COLUMN_5 || ITEM_GROUP.TENDUONGSU || ITEM_GROUP.NAMSINH || ITEM_GROUP.DIACHI || ITEM_GROUP.TEN || CHR(10);
            END LOOP;
                v_ARRAY(ITEM.v_STT).v_NGUOI_QLNVLQ_5:= COLUMN_5;


            -- v_NGUOIBV_QLIHP_DS_6 - HỌ TÊN NGƯỜI BẢO VỆ QUYỀN, LỢI ÍCH HỢP PHÁP CHO ĐƯƠNG SỰ - 6 -
            COLUMN_6 := '';

            FOR ITEMS IN (SELECT * 
                          FROM ADS_DON_THAMGIATOTUNG T2
                          WHERE T2.TUCACHTGTTID like 'TGTTDS%' AND ITEM.v_VUANID = T2.DONID)
            LOOP

                IF(ITEMS.TUCACHTGTTID LIKE 'TGTTDS_02') -- Luật sư
                            THEN COLUMN_6 := COLUMN_6 || '- ' || ITEMS.HOTEN||'; ' || ITEMS.TEN_VPLS || '; '|| ITEMS.DIACHI || ';'|| CHR(10);
                    ELSE 
                        COLUMN_6 := COLUMN_6 || '- ' || ITEMS.HOTEN||'; ' || NVL(ITEMS.HKTTCHITIET, ITEMS.TAMTRUCHITIET) || ';' || CHR(10) ;
                END IF;

            END LOOP;

			v_ARRAY(ITEM.v_STT).v_NGUOIBV_QLIHP_DS_6 := COLUMN_6;

		END LOOP;    

		-- v_QHPLKHITL_7 - QUAN HỆ PHÁP LUẬT KHI THỤ LÝ - 7 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(T1.V_QUANHEPHAPLUAT_NAME,NULL,T2.TEN,T1.V_QUANHEPHAPLUAT_NAME) v_QHPLKHITL_7
			FROM 
				TABLE(v_ARRAY) T1 
				LEFT JOIN DM_DATAITEM T2 ON T1.v_QUANHEPHAPLUATID=T2.ID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_QHPLKHITL_7:=ITEM.v_QHPLKHITL_7;
		END LOOP;

		-- v_ADBPKCTT_8 - ÁP DỤNG BIỆN PHÁP KHẨN CẤP TẠM THỜI Số, ngày tháng năm - 8 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOQD || CHR(10) ||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_ADBPKCTT_8
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_LOAI T3 on T3.ID=T2.LOAIQDID and T3.MA='ADBPTT'
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_ADBPKCTT_8:=ITEM.v_ADBPKCTT_8;
		END LOOP;

		-- v_CHUYENHS_VUVIEC_9 - CHUYỂN HỒ SƠ VỤ VIỆC Số, ngày tháng năm và nơi nhận - 9 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
						T2.SOQD||CHR(10)||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY') ||CHR(10)|| TA.MA_TEN
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_CHUYENHS_VUVIEC_9
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_QUYETDINH T2 
                LEFT JOIN DM_QD_QUYETDINH QD ON T2.QUYETDINHID=QD.ID ON T1.v_VUANID=T2.DONID 
                LEFT JOIN ADS_CHUYEN_NHAN_AN CN ON CN.VUANID=T2.DONID
                LEFT JOIN DM_TOAAN TA ON TA.ID=CN.TOANHANID
                WHERE QD.ID=4 -- QD.ID=4 Quyết định chuyển vụ án vì không thuộc thẩm quyền
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_CHUYENHS_VUVIEC_9:=ITEM.v_CHUYENHS_VUVIEC_9;
		END LOOP;

		-- v_TDC_10 - TẠM ĐÌNH CHỈ Số, ngày tháng năm - 10 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOQD || CHR(10) ||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_TDC_10
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_LOAI T3 on T3.ID=T2.LOAIQDID and T3.MA='TDC'
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_TDC_10:=ITEM.v_TDC_10;
		END LOOP;

		-- v_DC_11 - ĐÌNH CHỈ Số, ngày tháng năm - 11 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOQD || CHR(10) ||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_DC_11
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_LOAI T3 on T3.ID=T2.LOAIQDID and T3.MA='DC'
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_DC_11:=ITEM.v_DC_11;
		END LOOP;
		-- v_LYDO_12 - LÝ DO - 12 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, T1.V_VUANID
			FROM 
				TABLE(v_ARRAY) T1 
		) LOOP
            COLUMN_12 := '';
            FOR ITEMS IN (SELECT DONID, REGEXP_REPLACE(DMQD.TEN, '^\d+-[A-Za-z]+\. Quyết định ', '') AS TENQD ,
                                       DECODE(DMLD.TEN, NULL, '', 'Lý do: ' || DMLD.TEN) LYDO
                            FROM ADS_SOTHAM_QUYETDINH T2
                                INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = T2.QUYETDINHID
                                LEFT JOIN DM_QD_QUYETDINH_LYDO DMLD ON DMLD.ID = T2.LYDOID
                            WHERE (DMQD.TEN LIKE '%đình chỉ%' or DMQD.TEN like '%biện pháp%') AND T2.DONID = ITEM.v_VUANID
                            --GROUP BY DONID
                        )
            LOOP
                 COLUMN_12 := COLUMN_12 || '- QĐ ' || ITEMS.TENQD || '. ' ||  ITEMS.LYDO || CHR(10);
            END LOOP;

                v_ARRAY(ITEM.v_STT).v_LYDO_12 := COLUMN_12;

		END LOOP;

		-- v_CONGNHAN_THOATHUAN_DS_13 - CÔNG NHẬN SỰ THỎA THUẬN CỦA ĐƯƠNG SỰ  -- Số, ngày tháng năm - 13 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOQD || CHR(10) ||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_CONGNHAN_THOATHUAN_DS_13
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_LOAI T3 on T3.ID=T2.LOAIQDID and t3.MA='CNTT'
			GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_CONGNHAN_THOATHUAN_DS_13:=ITEM.v_CONGNHAN_THOATHUAN_DS_13;
		END LOOP;

		-- v_HDXX_VKS_TKPT_14 - HỘI ĐỒNG XÉT XỬ, ĐẠI DIỆN VIỆN KIỂM SÁT, THƯ KÝ PHIÊN TÒA -- Ghi đầy đủ họ tên - 14 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || NVL(T3.HOTEN,'')||NVL(T4.HOTEN,'')||
						' ('||DECODE(T2.MAVAITRO,'HTND','HTND','KSV','KSV','THAMPHAN','TPCT','THAMPHANDUKHUYET','TPDK','THAMPHANHDXX','TPTV','THUKY','TK','THUKYDUKHUYET','TKDK','')||')'
						AS VARCHAR2(4000)
					), CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT) v_HDXX_VKS_TKPT_14
			FROM 
				TABLE(v_ARRAY) T1
                INNER JOIN ( select tp.* from ADS_SOTHAM_HDXX tp where tp.MAVAITRO!='THAMPHAN' --loại thẩm phán ra khỏi danh sách
                              union all
                              select tp.* from ADS_SOTHAM_HDXX tp
                                WHERE tp.MAVAITRO='THAMPHAN' --xử lý, lấy 1 thẩm phán mới nhất
                                and EXISTS(SELECT 'X' FROM (
                                                    SELECT TT.DONID,TT.ID FROM (  
                                                     SELECT DONID,FIRST_VALUE(CANBOID) OVER (PARTITION BY DONID ORDER BY NGAYTAO DESC) ID
                                                     FROM  ADS_SOTHAM_HDXX WHERE MAVAITRO='THAMPHAN'
                                                        )TT GROUP BY TT.DONID,TT.ID
                                                 )XX WHERE XX.ID=TP.CANBOID AND XX.DONID=TP.DONID
                                             )
                         ) T2 on T1.v_VUANID=T2.DONID
				LEFT JOIN DM_CANBO T3 ON T3.ID=T2.CANBOID AND INSTR('THAMPHAN,THAMPHANHDXX,THAMPHANDUKHUYET,THUKY,THUKYDUKHUYET,HTND',T2.MAVAITRO)>0
				LEFT JOIN DM_CANBOVKS T4 ON T4.ID=T2.CANBOID AND INSTR('HTND,KSV',T2.MAVAITRO)>0
        group by T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_HDXX_VKS_TKPT_14:=ITEM.v_HDXX_VKS_TKPT_14;
		END LOOP;

		-- v_BA_QDST_15 - BẢN ÁN, QUYẾT ĐỊNH SƠ THẨM Số, ngày tháng năm - 15 - 
		FOR ITEM IN (
            SELECT 
                T1.v_STT, 
                LISTAGG(
                T2.SOBANAN || CHR(10) || TO_CHAR(T2.NGAYTUYENAN,'DD/MM/YYYY'),
                CHR(10)
            ) WITHIN GROUP (ORDER BY T1.v_STT) v_BA_QDST_15
            FROM 
                TABLE(v_ARRAY) T1
                INNER JOIN ADS_SOTHAM_BANAN T2 ON T1.v_VUANID = T2.DONID
            GROUP BY T1.v_STT

            UNION ALL

            SELECT 
                T1.v_STT, 
                LISTAGG(
                T2.SOQD || CHR(10) || TO_CHAR(T2.NGAYQD,'DD/MM/YYYY'),
                CHR(10)
            ) WITHIN GROUP (ORDER BY T1.v_STT) v_BA_QDST_15
            FROM 
                TABLE(v_ARRAY) T1
                INNER JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID = T2.DONID
                INNER JOIN DM_QD_QUYETDINH QD ON T2.QUYETDINHID = QD.ID AND KET_THUC = 1
            --WHERE T2.ISCONGBOQD = 1
            GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_BA_QDST_15:=ITEM.v_BA_QDST_15;
		END LOOP;

		-- v_QHPLMATAGQ_16 - QUAN HỆ PHÁP LUẬT MÀ TOÀ ÁN GIẢI QUYẾT - 16 - 
		-- v_TTND_BA_QD_TA_ST_17 - TÓM TẮT NỘI DUNG BẢN ÁN, QUYẾT ĐỊNH CỦA TOÀ ÁN CẤP SƠ THẨM - 17 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, T1.v_VUANID,
				DECODE(T2.QUANHEPHAPLUAT_NAME,NULL,T3.TEN,T2.quanhephapluat_name) v_QHPLMATAGQ_16, T2.NOIDUNG v_TTND_BA_QD_TA_ST_17
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_BANAN T2 ON T1.v_VUANID=T2.DONID
				LEFT JOIN DM_DATAITEM T3 ON T3.ID=T2.QUANHEPHAPLUATID

            union

            SELECT 
				T1.v_STT, T1.v_VUANID, 
				DECODE(T2.QUANHEPHAPLUAT,NULL,T3.CASE_NAME,T2.QUANHEPHAPLUAT) v_QHPLMATAGQ_16, LISTAGG(T2.NOIDUNG, CHR(10)) WITHIN GROUP (ORDER BY T2.NGAYQD) v_TTND_BA_QD_TA_ST_17
			FROM 
				TABLE(v_ARRAY) T1 
                INNER JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
                INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = T2.QUYETDINHID AND DMQD.KET_THUC = 1
				LEFT JOIN DM_QHPL_TK T3 ON T3.ID = T2.QHPLTKID
            GROUP BY T1.v_STT, T1.v_VUANID,  DECODE(T2.QUANHEPHAPLUAT,NULL,T3.CASE_NAME,T2.QUANHEPHAPLUAT)

		) LOOP
			v_ARRAY(ITEM.v_STT).v_QHPLMATAGQ_16:= v_ARRAY(ITEM.v_STT).v_QHPLMATAGQ_16 || ITEM.v_QHPLMATAGQ_16;
			v_ARRAY(ITEM.v_STT).v_TTND_BA_QD_TA_ST_17 := v_ARRAY(ITEM.v_STT).v_TTND_BA_QD_TA_ST_17 || ITEM.v_TTND_BA_QD_TA_ST_17;

		END LOOP;    

		-- v_KQGQYC_HUYQDCABIET_18 - KẾT QUẢ GIẢI QUYẾT YÊU CẦU HỦY QUYẾT ĐỊNH CÁ BIỆT -- Số, ngày tháng năm, cơ quan ban hành (nếu có) - 18 - 

		-- v_XETXULUUDONG_19 - XÉT XỬ LƯU ĐỘNG - 19 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(T2.XETXULUUDONG,1,'X','') v_XETXULUUDONG_19
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_BANAN T2 ON T1.v_VUANID=T2.DONID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_XETXULUUDONG_19:=ITEM.v_XETXULUUDONG_19;
		END LOOP;

		-- v_APDUNGANLE_20 - ÁP DỤNG ÁN LỆ - 20 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(T2.APDUNGANLE,1,'X','') v_APDUNGANLE_20
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_BANAN T2 ON T1.v_VUANID=T2.DONID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_APDUNGANLE_20:=ITEM.v_APDUNGANLE_20;
		END LOOP;

		-- v_GQ_TTRG_21 - GIẢI QUYẾT THEO THỦ TỤC RÚT GỌN -- Số, ngày tháng năm - 21 -  
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				T2.SOQD || CHR(10) || TO_CHAR(T2.NGAYQD,'DD/MM/YYYY') v_GQ_TTRG_21
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID
        inner join DM_QD_QUYETDINH T3 on T3.ID=T2.QUYETDINHID and T3.MA='77-DS'
		) LOOP
			v_ARRAY(ITEM.v_STT).v_GQ_TTRG_21:=ITEM.v_GQ_TTRG_21;
		END LOOP;
        -- V_PT_RUTKINHNGHIEM - TÒA ÁN TỔ CHỨC PHIỀN TÒA RÚT KINH NGHIỆM  thể hiện dấu x 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(T2.ST_ISRUTKN,1,'X','') V_PT_RUTKINHNGHIEM
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SAUXETXU T2 ON T1.v_VUANID=T2.VUANID
		) LOOP
			v_ARRAY(ITEM.v_STT).V_PT_RUTKINHNGHIEM:=ITEM.V_PT_RUTKINHNGHIEM;
		END LOOP;
		-- v_COYEUTONUOCNGOAI_22 - CÓ YẾU TỐ NƯỚC NGOÀI - 22 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(T2.YEUTONUOCNGOAI,1,'X','') v_COYEUTONUOCNGOAI_22
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_BANAN T2 ON T1.v_VUANID=T2.DONID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_COYEUTONUOCNGOAI_22:=ITEM.v_COYEUTONUOCNGOAI_22;
		END LOOP;

		-- v_VIECDS_23 - VIỆC DÂN SỰ - 23 -        
        FOR ITEM IN (SELECT T1.v_STT, T1.V_VUANID FROM TABLE(v_ARRAY) T1)
        LOOP
            COLUMN_23 := ' ';

            IF(COLUMN_23 LIKE ' ') THEN
                BEGIN
                        SELECT DECODE(T2.OPTIONS,1,'X','') INTO COLUMN_23
                        FROM ADS_SOTHAM_BANAN T1 
                            LEFT JOIN DM_QHPL_TK T2 ON T1.QHPLTKID=T2.ID
                         WHERE T1.DONID = ITEM.V_VUANID;
                EXCEPTION WHEN NO_DATA_FOUND THEN COLUMN_23 := ' ';
                END; 
            END IF;

            IF(COLUMN_23 LIKE ' ') THEN
                BEGIN
                        SELECT DECODE(T2.OPTIONS,1,'X','') INTO COLUMN_23
                        FROM ADS_SOTHAM_QUYETDINH T1
                            INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = T1.QUYETDINHID  AND DMQD.KET_THUC = 1
                            LEFT JOIN DM_QHPL_TK T2 ON T2.ID = T1.QHPLTKID
                        WHERE T1.DONID = ITEM.V_VUANID
                        ORDER BY T1.ID DESC FETCH FIRST ROW ONLY;

                EXCEPTION WHEN NO_DATA_FOUND THEN COLUMN_23 := ' '; 
                END; 
            END IF;     

            IF(COLUMN_23 LIKE ' ') THEN
                BEGIN   
                        SELECT DECODE(T2.OPTIONS,1,'X','')  INTO COLUMN_23
                        FROM ADS_SOTHAM_THULY T1 
                            LEFT JOIN DM_QHPL_TK T2 ON T1.QHPLTKID=T2.ID
                        WHERE T1.DONID = ITEM.V_VUANID
                        ORDER BY T1.ID DESC FETCH FIRST ROW ONLY;
                EXCEPTION WHEN NO_DATA_FOUND THEN COLUMN_23 := ' ';
                END;  
            END IF;    

            v_ARRAY(ITEM.v_STT).v_VIECDS_23 := COLUMN_23;

		END LOOP;      

		-- v_KC_24 - KHÁNG CÁO - 24 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				 DECODE(SIGN(COUNT(T2.DONID)),1,TO_CHAR(T2.NGAYKHANGCAO,'dd/MM/yyyy'),'') v_KC_24--DECODE(SIGN(COUNT(T2.DONID)),1,'X','')
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_KHANGCAO T2 ON T1.v_VUANID=T2.DONID
        GROUP BY T1.v_STT,TO_CHAR(T2.NGAYKHANGCAO,'dd/MM/yyyy')
		) LOOP
			v_ARRAY(ITEM.v_STT).v_KC_24:=ITEM.v_KC_24;
		END LOOP;

		-- v_KN_25 - KHÁNG NGHỊ -- Số, ngày tháng năm - 25 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					T2.SOKN || CHR(10) ||
					TO_CHAR(T2.NGAYKN,'DD/MM/YYYY')
					, CHR(10)
				) WITHIN GROUP (ORDER BY T1.v_STT)  v_KN_25
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN ADS_SOTHAM_KHANGNGHI T2 ON T1.v_VUANID=T2.DONID
			GROUP BY 
				T1.v_STT				
		) LOOP
			v_ARRAY(ITEM.v_STT).v_KN_25:=ITEM.v_KN_25;
		END LOOP;

		-- v_CHUYENHS_TA_PT_26 - CHUYỂN HỒ SƠ CHO TÒA ÁN CẤP PHÚC THẨM Ngày tháng năm - 26 - 
        FOR ITEM IN (
                    SELECT 
                        T1.v_STT, 
                        LISTAGG(
                            TO_CHAR(T2.NGAYGIAO,'DD/MM/YYYY')
                            , CHR(10)
                        ) WITHIN GROUP (ORDER BY T1.v_STT) v_CHUYENHS_TA_PT_26
                    FROM 
                        TABLE(v_ARRAY) T1 
                        LEFT JOIN ADS_CHUYEN_NHAN_AN T2 ON  T1.v_VUANID=T2.VUANID
                        LEFT JOIN DM_TOAAN TA ON TA.ID=T2.TOANHANID
                        WHERE TRUONGHOPGIAONHANID in(267,268,269) and TA.MA_TEN is not null
                        --267 Do có kháng cáo phúc thẩm 
                        --268 Do có kháng cáo và kháng nghị phúc thẩm 
                        --269 Do có kháng nghị phúc thẩm
                    GROUP BY T1.v_STT
                ) LOOP
                    v_ARRAY(ITEM.v_STT).v_CHUYENHS_TA_PT_26:=ITEM.v_CHUYENHS_TA_PT_26;
                END LOOP;

		-- v_QD_TA_PT_27 - QUYẾT ĐỊNH CỦA TÒA ÁN CẤP PHÚC THẨM Số, ngày tháng năm Tóm tắt phần quyết định - 27 - 
        FOR ITEM IN (
			SELECT 
				T1.v_STT
                ,T3.SOQD|| CHR(10) ||TO_CHAR(T3.NGAYQD,'DD/MM/YYYY')|| CHR(10) || T3.NOIDUNGQD|| CHR(10)||
                T2.SOBANAN|| CHR(10) || TO_CHAR(T2.NGAYTUYENAN,'DD/MM/YYYY') || CHR(10) ||  T2.NOIDUNGQD|| CHR(10) 
                v_QD_TA_PT_27
			FROM 
				TABLE(v_ARRAY) T1 
				LEFT JOIN (SELECT B.ID,B.DONID,B.SOBANAN,B.NGAYTUYENAN,BKQ.TEN NOIDUNGQD 
                                        FROM ADS_PHUCTHAM_BANAN B
                                        LEFT JOIN DM_KETQUA_PHUCTHAM BKQ ON BKQ.ID = B.KETQUAPHUCTHAMID) T2 ON T1.v_VUANID=T2.DONID
                LEFT JOIN (SELECT Q.SOQD, Q.NGAYQD,Q.DONID,Q.QUYETDINHID,KQ.TEN NOIDUNGQD 
                                        FROM ADS_PHUCTHAM_QUYETDINH Q 
                                        LEFT JOIN DM_QD_QUYETDINH D ON D.ID=Q.QUYETDINHID 
                                        LEFT JOIN DM_KETQUA_PHUCTHAM KQ ON KQ.ID = Q.KETQUAID
                                                WHERE D.KET_THUC = 1) T3 ON T1.v_VUANID=T3.DONID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_QD_TA_PT_27:=ITEM.v_QD_TA_PT_27;
		END LOOP;

		-- v_GHICHU_28 - GHI CHÚ - 28 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
                LISTAGG(
					decode(T2.SOQD,null,null,'QĐXX:'||T2.SOQD ||', ')||
					TO_CHAR(T2.NGAYQD,'DD/MM/YYYY') ||DL1.TENDUONGSU ||PT1.TENDUONGSU
                    ||DECODE(QHLD.ID,NULL,NULL,'Quá hạn luật định')
				) WITHIN GROUP (ORDER BY T1.v_STT)  v_GHICHU_28
			FROM 
				TABLE(v_ARRAY) T1 
                LEFT JOIN ADS_SOTHAM_QUYETDINH T2 ON T1.v_VUANID=T2.DONID and T2.quyetdinhid=46 --47-DS. Quyết định đưa vụ án ra xét xử sơ thẩm
                LEFT JOIN DON_CHITIET PT ON PT.DONID=T1.v_VUANID AND PT.LOAIDON=5 -- DC.LOAIDON=5 Đơn có yêu cầu phản tố
                LEFT JOIN ( 
                            SELECT 'YCPT:'||LISTAGG(DS.TENDUONGSU,',')  WITHIN GROUP (ORDER BY TENDUONGSU) TENDUONGSU,CH.DONCHITIETID
                            FROM DON_DUONGSU_CHITIET CH 
                            LEFT JOIN ADS_DON_DUONGSU DS ON DS.ID=CH.DUONGSUID
                            GROUP BY CH.DONCHITIETID
                            ) PT1 ON PT1.DONCHITIETID=PT.ID
                LEFT JOIN DON_CHITIET DL ON DL.DONID=T1.v_VUANID AND DL.LOAIDON=6 -- DC.LOAIDON=6 Đơn có yêu cầu độc lập
                LEFT JOIN ( 
                            SELECT 'YCĐL:'||LISTAGG(DS.TENDUONGSU,',')  WITHIN GROUP (ORDER BY TENDUONGSU) TENDUONGSU,CH.DONCHITIETID
                            FROM DON_DUONGSU_CHITIET CH 
                            LEFT JOIN ADS_DON_DUONGSU DS ON DS.ID=CH.DUONGSUID
                            GROUP BY CH.DONCHITIETID
                            ) DL1 ON DL1.DONCHITIETID=DL.ID
                 LEFT JOIN (                       
                            SELECT TL.ID FROM ADS_SOTHAM_THULY TL
                            LEFT JOIN ADS_SOTHAM_QUYETDINH QSV ON TL.DONID=QSV.DONID
                            LEFT JOIN DM_QD_LOAI QDL ON QSV.LOAIQDID=QDL.ID
                            LEFT JOIN ADS_SOTHAM_BANAN BA ON BA.DONID =TL.DONID
                            WHERE BA.ID IS NOT NULL and BA.TK_ISQUAHAN =1 --phải lấy check ở quấ hạn luật định ở bản án
                            GROUP BY TL.ID )QHLD ON QHLD.ID=T1.v_THULYID           
                GROUP BY T1.v_STT
		) LOOP
			v_ARRAY(ITEM.v_STT).v_GHICHU_28:=ITEM.v_GHICHU_28;
		END LOOP;

	END;
    PROCEDURE SO_HONNHAN_SOTHAM
	(
		 in_TOAANID IN NUMBER,
		 in_TOAANCAPCON IN NVARCHAR2,
		 in_NGAYBATDAU IN NVARCHAR2,
		 in_NGAYKETTHUC IN NVARCHAR2,
		 curReturn OUT SYS_REFCURSOR
	) AS
		v_ARRAY T_HONNHAN_SOTHAM;
		v_IDS T_ID;
	BEGIN
		--
		--TÒA ÁN CẤP CON
		v_IDS:=T_ID();
		IF (in_TOAANCAPCON='TRUE') THEN
			SELECT R_ID(ID) BULK COLLECT INTO v_IDS FROM DM_TOAAN WHERE CAPCHAID=in_TOAANID;
		END IF;
		v_IDS.EXTEND();
		v_IDS(v_IDS.COUNT):=R_ID(in_TOAANID);
		--
		--XAC DINH ID THU LY AN THEO THAM SO
		SELECT R_HONNHAN_SOTHAM(
			v_STT=>row_number() over (order by TL.ID),
			v_THULYID=>TL.ID,
			v_VUANID=>TL.DONID,
			v_TOAANID=>TL.TOAANID,
			v_QUANHEPHAPLUATID=>NULL,
			v_TL_1=>NULL,
			v_ND_NYC_2=>NULL,
			v_BD_NLQ_HNGD_3=>NULL,
			v_DKK_CQTC_4=>NULL,
			v_NGUOI_QLNVLQ_5=>NULL,
			v_NGUOIBV_QLIHP_DS_6=>NULL,
			v_QHPLKHITL_7=>NULL,
			v_LYDO_LYHON_8=>NULL,
			v_SOCONCHUATHANHNIEN_9=>NULL,
			v_ADBPKCTT_10=>NULL,
			v_CHUYENHS_VUVIEC_11=>NULL,
			v_TDC_12=>NULL,
			v_DC_13=>NULL,
			v_LYDO_14=>NULL,
			v_HOAGIAIDOANTU_15=>NULL,
			v_CONGNHAN_THOATHUAN_DS_16=>NULL,
			v_HDXX_VKS_TKPT_17=>NULL,
			v_BA_QDST_18=>NULL,
			v_QHPLTADAGQ_19=>NULL,
			v_TTND_BA_QD_TA_ST_20=>NULL,
			v_KQGQYC_HUYQDCABIET_21=>NULL,
			v_APDUNGANLE_22=>NULL,
			v_GQ_TTRG_23=>NULL,
			v_COYEUTONUOCNGOAI_24=>NULL,
			v_HN_GD_25=>NULL,
			v_KC_26=>NULL,
			v_KN_27=>NULL,
			v_CHUYENHS_TA_PT_28=>NULL,
			v_QD_TA_PT_29=>NULL,
			v_GHICHU_30=>NULL,
            V_NGAYTHULY=>NULL,
            V_SOTHULY=>NULL,
            V_QUANHEPHAPLUAT_NAME=>TL.QUANHEPHAPLUAT_NAME,
            V_PT_RUTKINHNGHIEM=>NULL
		)
		BULK COLLECT INTO v_ARRAY
        FROM (
            SELECT TL.*
            FROM AHN_SOTHAM_THULY TL 
                INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
            WHERE
                NGAYTHULY BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')

            UNION 
            SELECT TL.*
            FROM AHN_SOTHAM_THULY TL 
                INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
            WHERE
                NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND 
                (NOT EXISTS (SELECT  STQD.* FROM AHN_SOTHAM_QUYETDINH STQD 
                    INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 WHERE TL.DONID = STQD.DONID)
                AND NOT EXISTS (SELECT BA.* FROM AHN_SOTHAM_BANAN BA WHERE TL.DONID = BA.DONID))

            UNION 
            SELECT TL.*
            FROM AHN_SOTHAM_THULY TL 
                INNER JOIN TABLE(v_IDS) I ON I.v_ID=TL.TOAANID
            WHERE
                NGAYTHULY < TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND  
                (EXISTS (SELECT  STQD.* FROM AHN_SOTHAM_QUYETDINH STQD 
                    INNER JOIN DM_QD_QUYETDINH DMQD ON DMQD.ID = STQD.QUYETDINHID AND DMQD.KET_THUC = 1 
                    WHERE TL.DONID = STQD.DONID AND STQD.NGAYQD BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')
                    )
                OR EXISTS (SELECT BA.* FROM AHN_SOTHAM_BANAN BA 
                           WHERE TL.DONID = BA.DONID AND BA.NGAYTUYENAN BETWEEN TO_DATE(in_NGAYBATDAU,'DD/MM/YYYY') AND TO_DATE(in_NGAYKETTHUC,'DD/MM/YYYY')))
            ) TL;

            FILL_HONNHAN_SOTHAM(v_ARRAY);
		/*--
		FOR ITEM IN (SELECT * FROM TABLE(v_ARRAY)) LOOP
			DBMS_OUTPUT.PUT_LINE (ITEM.v_STT||' - '||ITEM.v_THULYID);
		END LOOP;
		--*/
		OPEN curReturn FOR SELECT * FROM TABLE(v_ARRAY) 
        ORDER by EXTRACT(YEAR FROM  V_NGAYTHULY),to_number(REGEXP_REPLACE(V_SOTHULY, '[^0-9]')),V_NGAYTHULY;
--	EXCEPTION 
--		WHEN OTHERS THEN 
--			RAISE_APPLICATION_ERROR(-20000, sqlerrm);
	END;
    	/*13 - SỔ THỤ LÝ VÀ KẾT QỦA GIẢI QUYẾT CÁC VỤ VIỆC HÔN NHÂN VÀ GIA ĐÌNH SƠ THẨM*/
	PROCEDURE FILL_HONNHAN_SOTHAM
	(
		v_ARRAY IN OUT T_HONNHAN_SOTHAM
	) AS        
        COLUMN_5 CLOB;
        COLUMN_6 CLOB;

        COLUMN_13 VARCHAR(2000);
        COLUMN_14 CLOB;
        COLUMN_25 VARCHAR(10);
	BEGIN	
		--v_ARRAY:=T_HONNHAN_SOTHAM();
		-- v_TL_1 - THỤ LÝ Số, ngày tháng năm - 1 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				T2.QUANHEPHAPLUATID v_QUANHEPHAPLUATID,
				T2.SOTHULY || CHR(10) || TO_CHAR(T2.NGAYTHULY,'DD/MM/YYYY') v_TL_1,
                T2.NGAYTHULY  V_NGAYTHULY,T2.SOTHULY V_SOTHULY

			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHN_SOTHAM_THULY T2 ON T1.v_THULYID=T2.ID
		) LOOP
			v_ARRAY(ITEM.v_STT).v_TL_1:=ITEM.v_TL_1;
			v_ARRAY(ITEM.v_STT).v_QUANHEPHAPLUATID:=ITEM.v_QUANHEPHAPLUATID;
            v_ARRAY(ITEM.v_STT).V_NGAYTHULY:=ITEM.V_NGAYTHULY;v_ARRAY(ITEM.v_STT).V_SOTHULY:=ITEM.V_SOTHULY;
		END LOOP;

		-- v_ND_NYC_2 - NGUYÊN ĐƠN HOẶC NGƯỜI YÊU CẦU Họ tên, năm sinh, địa chỉ - 2 - 
		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				LISTAGG(
					CAST(
						'- ' || T2.TENDUONGSU || '; ' ||
