		FOR ITEM IN (
			SELECT 
				T1.v_STT, 
				DECODE(T2.YEUTONUOCNGOAI,1,'X','') v_COYEUTONUOCNGOAI_24
			FROM 
				TABLE(v_ARRAY) T1 
				INNER JOIN AHN_SOTHAM_BANAN T2 ON T1.v_VUANID=T2.DONID
